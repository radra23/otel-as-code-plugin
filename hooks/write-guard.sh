#!/usr/bin/env bash
# hooks/write-guard.sh
# PreToolUse hook — blocks destructive overwrites of existing OTel bootstrap files.
# Exit 0 = allow the tool call. Exit 2 = BLOCK the tool call (reason written to stderr).
# IMPORTANT: in Claude Code a PreToolUse hook blocks ONLY on exit 2. Exit 1 (or any other
# non-zero) is a non-blocking error — the tool call PROCEEDS — so a block MUST use exit 2.
# (Ref: code.claude.com/docs/en/hooks-guide — exit codes.)
# Input: JSON on stdin with the Claude Code PreToolUse shape:
#   {"hook_event_name":"PreToolUse","tool_name":"Write","tool_input":{"file_path":"..."}}

set -euo pipefail

# Protected files the plugin generates and must not silently overwrite. A file is a CANDIDATE by
# name — a <stem>.<ext> bootstrap / otel-java.env / otelcol-*.yaml (the derived set in
# hooks/otel-paths.sh) OR a Terraform module file (main.tf / variables.tf / outputs.tf in ANY
# directory) — but is only BLOCKED if it actually carries the "generated by otel-as-code"
# ownership marker. That marker is what every generator stamps into its output, so:
#   - an unrelated project's hand-written tracing.js / main.tf (no marker) is never blocked, and
#   - our own output is caught wherever --output-dir put it (not only under */observability/*).

# Every file this hook runs or loads is named from ${CLAUDE_PLUGIN_ROOT}, never computed from the
# script's own location: Anthropic's plugin directory refuses a hook whose program it cannot read
# by name. Claude Code sets the variable; the tests and the Codex bridge run this script directly,
# so it defaults to the plugin folder above this file.
CLAUDE_PLUGIN_ROOT="${CLAUDE_PLUGIN_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

# Generated-file vocabulary, shared with session-summary.sh so the two cannot drift.
# Guarded: under `set -e` a failed source would abort with exit 1, which this hook's contract
# reads as BLOCK, bricking every Write/Edit in the repo over a broken install. An absent guard
# with a loud message is the better failure than a session where nothing can be written.
# shellcheck source=hooks/otel-paths.sh
if ! . "${CLAUDE_PLUGIN_ROOT}/hooks/otel-paths.sh" 2>/dev/null; then
  echo "otel-as-code write-guard: cannot load ${CLAUDE_PLUGIN_ROOT}/hooks/otel-paths.sh: overwrite protection is OFF." >&2
  echo "Reinstall the plugin; until then generated OTel files are not protected." >&2
  exit 0
fi

# Global force override via env var (manual use / CI). Per-file --force is handled below
# via the .claude/.otel-force sentinel so a slash-command flag can reach this hook process.
if [ "${OTEL_FORCE:-0}" = "1" ]; then
  exit 0
fi

# A Python that actually runs (python3 or python, by literal name), or PY="" when none does.
# If the helper itself can't load, PY stays empty and the no-Python branch below decides.
PY=""
# shellcheck source=hooks/otel-python.sh
. "${CLAUDE_PLUGIN_ROOT}/hooks/otel-python.sh" 2>/dev/null || PY=""

# Read JSON from stdin
INPUT=$(cat)

# Without Python the payload can't be parsed properly, but the target's file name can still be
# read with plain shell. Fail closed only when that name is one this plugin protects (a
# generated file, a Terraform module file, or the context cache) or can't be read at all, so a
# machine without Python can still edit everything else. Separators, Windows backslashes
# included, become `/` through a character class rather than an escape.
if [ -z "$PY" ]; then
  # One plain assignment per line, so the plugin directory's validator can read each command.
  # `|| true`: under pipefail a payload with no file_path would otherwise end the hook with exit
  # 1, which Claude Code treats as a non-blocking error, so the write would go through unchecked.
  FIELD=$(echo "$INPUT" | grep -o '"file_path"[^,}]*' || true)
  NAME=$(echo "$FIELD" | sed 's#[^[:alnum:]._-]#/#g')
  while [ "${NAME%/}" != "$NAME" ]; do NAME=${NAME%/}; done
  NAME=${NAME##*/}
  LOWER=$(echo "$NAME" | tr '[:upper:]' '[:lower:]')
  protected=0
  if [ -z "$NAME" ] || [ "$NAME" = "file_path" ]; then protected=1; fi
  if otel_is_generated_basename "$NAME"; then protected=1; fi
  if otel_is_tf_module_basename "$LOWER" || [ "$LOWER" = otel-context.json ]; then protected=1; fi
  if [ "$protected" -eq 0 ]; then
    echo "otel-as-code write-guard: no working python, so this write is not checked ($NAME is not an otel-as-code file)." >&2
    exit 0
  fi
  echo "otel-as-code write-guard: no WORKING python found: python3/python are absent or do not run" >&2
  echo "(on Windows, python3 may be a Microsoft Store alias stub that is on PATH but errors when run)." >&2
  echo "Blocking this write to ${NAME:-an unreadable path}, a file otel-as-code protects (fail closed)." >&2
  echo "Install a real Python 3, or set OTEL_HOOK_PYTHON to its path." >&2
  exit 2
fi

# Tool name and file path in one parse, as "<tool> <path>": a tool name has no space, so the
# first space splits them and a path that contains spaces stays whole.
PARSED=$(echo "$INPUT" | py -c "import sys,json; d=json.load(sys.stdin); print(d.get('tool_name',''), d.get('tool_input',{}).get('file_path',''))" 2>/dev/null || echo "")
TOOL=${PARSED%% *}
FILE_PATH=${PARSED#* }

# Only guard Write and Edit tools
if [ "$TOOL" != "Write" ] && [ "$TOOL" != "Edit" ]; then
  exit 0
fi

if [ -z "$FILE_PATH" ]; then
  exit 0
fi

# Confirm-before-write enforcement for business attributes. Business semantics are never
# assumed: any business attribute written to the context cache must carry "confirmed": true
# (set by /otel-business-attrs only after explicit user approval). Block otherwise: this
# turns the confirmation gate into a structural invariant rather than prose. A Write is checked
# on its content, an Edit on the file as the edit would leave it (hooks/otel-context-check.py).
# scripts/write_context.py, which the commands use to write the cache, applies the same rule.
# The path is normalised before matching (backslashes, `.` and `..`, letter case), so another
# spelling of the same file or a Windows path cannot step around the check. The normalisation
# lives in otel-force-match.py, the one place this hook already compares paths.
if py "${CLAUDE_PLUGIN_ROOT}/hooks/otel-force-match.py" --is-context "$FILE_PATH" 2>/dev/null; then
  UNCONFIRMED=$(echo "$INPUT" | py "${CLAUDE_PLUGIN_ROOT}/hooks/otel-context-check.py" 2>/dev/null || echo "")
  if [ -n "$UNCONFIRMED" ]; then
    echo "otel-as-code write-guard: refusing to write unconfirmed business attribute(s) to otel-context.json:" >&2
    echo "$UNCONFIRMED" | sed 's/^/  - /' >&2
    echo 'Business attributes must carry "confirmed": true before they are written.' >&2
    echo "Re-run /otel-business-attrs and confirm each attribute." >&2
    exit 2
  fi
fi

# Check if the file exists on disk
if [ ! -f "$FILE_PATH" ]; then
  exit 0  # File doesn't exist yet — new write is always allowed
fi

# A file is blocked when it is a candidate by name, bootstrap/collector/java-env basenames
# (derived in otel-paths.sh) OR a Terraform module file in ANY directory (so a custom
# --output-dir is covered, not just */observability/*), AND the existing file carries the
# ownership marker every generator stamps ("Generated by otel-as-code" / "generated by
# otel-as-code"). The marker is what keeps the guard from blocking a file we did not generate,
# and what lets it catch our output regardless of directory.
if { otel_is_generated_path "$FILE_PATH" || otel_is_tf_module_basename "$(basename "$FILE_PATH")"; } && grep -qi 'generated by otel-as-code' "$FILE_PATH" 2>/dev/null; then
  # Path-scoped --force: when a /otel-* command is invoked with --force it writes the absolute
  # paths it intends to overwrite into .claude/.otel-force (one per line) and removes the file
  # afterwards. Honor it only for the listed paths, so --force never blanket-disables the guard.
  # Checked only here, for a write that would otherwise be blocked, so other writes never pay
  # for the Python call.
  #
  # Both sides are normalised before comparison rather than compared as raw strings. The tool
  # reports `file_path` in the host's own convention: on Windows a backslashed
  # `C:<backslash>Users<backslash>me<backslash>repo<backslash>src<backslash>tracing.ts`, while the sentinel is written from a shell where the
  # same file is `/c/Users/me/repo/src/tracing.ts`, and Codex's apply_patch reports paths
  # relative to the session cwd. An exact-string match can never succeed across those shapes,
  # which silently turned --force into a no-op. See hooks/otel-force-match.py.
  PROJECT_DIR="${CLAUDE_PROJECT_DIR:-$(pwd)}"
  FORCE_FILE="$PROJECT_DIR/.claude/.otel-force"
  if [ -f "$FORCE_FILE" ] && py "${CLAUDE_PLUGIN_ROOT}/hooks/otel-force-match.py" "$FILE_PATH" "$PROJECT_DIR" "$FORCE_FILE" 2>/dev/null; then
    exit 0
  fi
  echo "otel-as-code write-guard: blocking overwrite of existing generated OTel file: $FILE_PATH" >&2
  echo "Re-run the originating /otel-* command with --force to overwrite." >&2
  exit 2
fi

exit 0
