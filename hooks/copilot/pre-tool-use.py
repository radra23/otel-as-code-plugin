#!/usr/bin/env python3
# hooks/copilot/pre-tool-use.py
# GitHub Copilot CLI preToolUse adapter for otel-as-code.
#
# Maps Copilot's `create`/`edit` to Claude's Write/Edit and runs hooks/write-guard.sh (overwrite
# protection + confirm-before-write on the context cache) on it, unchanged. A block (exit 2 +
# stderr) becomes Copilot's top-level {"permissionDecision": "deny"} on stdout: on Copilot CLI
# 1.0.56 exit 2 is logged and the write still runs, and only the JSON denies
# (docs/agents/copilot-spike.md, rows 3a/3b). Shared plumbing lives in _copilot.py.
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _copilot import bridge_env, claude_tool, is_context_path, read_payload, resolves_to_cache, run_hook


def checkable(name, tool_input):
    """True when hooks/otel-context-check.py can see what this write leaves in the cache."""
    if name == "Write":
        return isinstance(tool_input["content"], str)
    old, new = tool_input["old_string"], tool_input["new_string"]
    return isinstance(old, str) and bool(old) and isinstance(new, str)


def deny(reason):
    print(json.dumps({"permissionDecision": "deny", "permissionDecisionReason": reason}))


def main(payload):
    tool = claude_tool(payload)
    if tool is None:
        return
    # The hook process runs in the plugin's install folder; the user's repo is the payload's cwd.
    cwd = payload.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
    path = tool[1]["file_path"]
    if resolves_to_cache(path, cwd) and not is_context_path(path):
        deny("otel-as-code write-guard: this write reaches .claude/otel-context.json through "
             "another name (a link or an alias), so its business attributes can't be checked. "
             "Write the cache by its own path.")
        return
    if resolves_to_cache(path, cwd) and not checkable(*tool):
        # The cache check reads a Write's content, or rebuilds the file by replacing an Edit's
        # old_string; anything else it can't read it lets through, so refuse it here.
        deny("otel-as-code write-guard: this write to .claude/otel-context.json doesn't give the "
             "file's content (or, for an edit, the text to replace and its replacement) as text, "
             "so its business attributes can't be checked. Write the whole file instead.")
        return
    proc = run_hook("write-guard.sh", path, None, cwd, bridge_env(cwd), tool=tool)
    if proc.returncode == 2:  # exit 2 = block in write-guard.sh; any other code allows, as in Claude Code
        deny((proc.stderr or "otel-as-code guardrail blocked this write.").strip())


def protected(path, cwd):
    """True when write-guard would refuse to overwrite `path` without --force: an existing file
    with a generated name (hooks/otel-paths.sh, the guard's own list) that carries the ownership
    marker. True as well when that can't be worked out, since this is only asked after a failure."""
    full = os.path.join(cwd, path)
    try:
        with open(full, encoding="utf-8", errors="replace") as f:
            if "generated by otel-as-code" not in f.read().lower():
                return False
    except FileNotFoundError:
        return False  # a new file is always allowed, as in write-guard.sh
    except OSError:
        return True
    paths_sh = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "otel-paths.sh")
    try:
        proc = subprocess.run(
            ["bash", "-c", '. "$1" && { otel_is_generated_path "$2" || otel_is_tf_module_basename "$(basename "$2")"; }',
             "_", paths_sh, full], capture_output=True, timeout=10)
    except Exception:  # noqa: BLE001
        return True
    return proc.returncode != 1  # 0 = a generated name; anything but a clean "no" counts as yes


def on_bridge_error(exc, payload):
    """What Copilot sees when this adapter itself fails (a bug here, a cwd that doesn't exist, an
    unreadable plugin file), as opposed to write-guard.sh deciding to block.

    Fail closed for the files the guard exists for, the generated files and the context cache:
    a bridge bug must not be the way one gets overwritten unchecked. Every other write goes
    ahead, so a bridge bug never stops someone editing their own code."""
    try:
        tool = claude_tool(payload)
    except Exception:  # noqa: BLE001
        tool = None
    if tool is None:
        return  # not a write this bridge checks
    path = tool[1]["file_path"]
    cwd = payload.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
    try:
        guarded = is_context_path(path) or resolves_to_cache(path, cwd) or protected(path, cwd)
    except Exception:  # noqa: BLE001
        guarded = True
    if guarded:
        deny("otel-as-code write-guard: the Copilot bridge failed (" + type(exc).__name__ + ": "
             + str(exc) + "), so this write to a file the guard protects could not be checked and "
             "is refused. Report it at https://github.com/radra23/otel-as-code-plugin/issues.")


if __name__ == "__main__":
    event = read_payload()
    try:
        main(event)
    except Exception as e:  # noqa: BLE001  (every failure goes through one policy)
        on_bridge_error(e, event)
