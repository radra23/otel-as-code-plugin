#!/usr/bin/env bash
# tests/enrich-clients.test.sh: offline tests of /otel-enrich --clients (scripts/enrich.py clients,
# client, span --client, and scripts/client-coverage.json). Real files in a temp project; the
# client spans are RUN against a stub OpenTelemetry API that records the kind and attributes they
# ask for. No network (tests/e2e/enrich-clients.sh runs the real packages). Needs node.
set -uo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD
pass=0; fail=0
check() { if eval "$2"; then echo "PASS: $1"; pass=$((pass+1)); else echo "FAIL: $1"; fail=$((fail+1)); fi; }
enrich() { python3 "$ROOT/scripts/enrich.py" "$@"; }
TMPD=$(mktemp -d); trap 'rm -rf "$TMPD"' EXIT
snap() { (cd "$1" && find . -type f -exec shasum {} + | sort) > "$TMPD/snap"; }
same() { (cd "$1" && find . -type f -exec shasum {} + | sort) | cmp -s - "$TMPD/snap"; }
# refused <name> <dir> <expected words> <enrich args...>: exit 2, one REFUSED line with those
# words, and nothing written.
refused() {
  local name="$1" dir="$2" words="$3" msg rc; shift 3
  snap "$dir"
  msg=$(enrich "$@" 2>&1); rc=$?
  check "$name" '[ "$rc" -eq 2 ] && echo "$msg" | grep -q "^REFUSED: " && echo "$msg" | grep -qi -- "$words" && same "$dir"'
}
# status <dir> <client> [args]: that client's status in the report, or "absent".
status() {
  local dir="$1" client="$2"; shift 2
  enrich clients --root "$dir" --json "$@" | python3 -c '
import json, sys
rows = {r["client"]: r["status"] for r in json.load(sys.stdin)["clients"]}
print(rows.get(sys.argv[1], "absent"))' "$client"
}
GOLDEN_PY=tests/snapshots/instrument/python
GOLDEN_JS=tests/snapshots/instrument/nodejs

# ================================================================== the table
check "table: every Python row names a package, module and class, and a known signal" \
  'python3 - <<PY
import json, sys
t = json.load(open("scripts/client-coverage.json"))
rows = t["python"]["packages"]
labels = [r["label"] for r in rows]
ok = len(labels) == len(set(labels)) and all(
    r["package"].startswith("opentelemetry-instrumentation-") and r["module"].startswith("opentelemetry.instrumentation.")
    and r["class"].endswith("Instrumentor") and r["signal"] in ("db", "messaging")
    and (r["clients"] or r.get("stdlib")) for r in rows)
ok = ok and all(top in labels and all(u in labels for u in under) for top, under in t["python"]["layers"].items())
n = t["nodejs"]
ok = ok and not (set(n["bundle"]) & set(n["none"])) and not (set(n["bundle"]) & set(n["manual"])) and not (set(n["manual"]) & set(n["none"]))
ok = ok and all(v["signal"] in ("db", "messaging") and v["system"] for v in n["none"].values())
sys.exit(0 if ok else 1)
PY'

# ================================================================== Python: the report
P="$TMPD/py"; mkdir -p "$P"
cp tests/enrich/py-clients/app.py "$GOLDEN_PY/tracing.py" "$GOLDEN_PY/requirements.txt" "$P/"
cp -R "$P" "$TMPD/py-orig"
check "python: a standard-library client is found by its import" '[ "$(status "$P" sqlite3)" = install ]'
check "python: the report says what was read and that other clients are not checked" \
  'out=$(enrich clients --root "$P"); echo "$out" | grep -q "read: requirements.txt, imports" && echo "$out" | grep -q "any other database or queue client is not checked\|Any other database or queue client is not checked"'
check "python: an import of sqlite3 in the generated bootstrap alone would not count" \
  'mkdir -p "$TMPD/noimp" && cp "$GOLDEN_PY/requirements.txt" "$TMPD/noimp/" && printf "# generated by otel-as-code\nimport sqlite3\n" > "$TMPD/noimp/tracing.py" && [ "$(status "$TMPD/noimp" sqlite3)" = absent ]'
mkdir -p "$TMPD/many"
printf 'fastapi>=0.110\nSQLAlchemy[asyncio]>=2.0\npsycopg2-binary==2.9.9\nredis>=5 ; python_version >= "3.9"\nPyMySQL\n-r other.txt\n# celery\nopentelemetry-instrumentation-fastapi>=0.66b2\nopentelemetry-instrumentation-redis>=0.66b2\n' > "$TMPD/many/requirements.txt"
check "python: names are matched whatever their case, extras, pins or markers" \
  '[ "$(status "$TMPD/many" sqlalchemy)" = install ] && [ "$(status "$TMPD/many" redis)" = turn-on ]'
check "python: a driver under SQLAlchemy is left to SQLAlchemy (two spans per query otherwise)" \
  '[ "$(status "$TMPD/many" psycopg2)" = layered ] && [ "$(status "$TMPD/many" pymysql)" = layered ] && enrich clients --root "$TMPD/many" | grep -q "psycopg2 .*two spans per query"'
check "python: a commented-out requirement and an -r line are not clients" '[ "$(status "$TMPD/many" celery)" = absent ]'
printf 'from opentelemetry.instrumentation.redis import RedisInstrumentor\nRedisInstrumentor().instrument()\n' > "$TMPD/many/otel_setup.py"
check "python: installed and turned on anywhere in the service reads as enabled" \
  '[ "$(status "$TMPD/many" redis)" = enabled ] && enrich clients --root "$TMPD/many" | grep -q "turned on in otel_setup.py"'
mkdir -p "$TMPD/pp"
printf '[project]\nname = "svc"\ndependencies = [\n  "fastapi>=0.110",\n  "asyncpg>=0.29",\n  "pika",\n]\n' > "$TMPD/pp/pyproject.toml"
check "python: pyproject.toml dependencies are read" \
  '[ "$(status "$TMPD/pp" asyncpg)" = install ] && [ "$(status "$TMPD/pp" pika)" = install ]'
mkdir -p "$TMPD/poetry"
printf '[tool.poetry.dependencies]\npython = "^3.12"\npymongo = "^4.6"\n\n[tool.poetry.group.dev.dependencies]\nkafka-python = "*"\n' > "$TMPD/poetry/pyproject.toml"
check "python: poetry dependencies are read, dev groups are not" \
  '[ "$(status "$TMPD/poetry" pymongo)" = install ] && [ "$(status "$TMPD/poetry" kafka-python)" = absent ]'
mkdir -p "$TMPD/empty"
refused "python: a directory with no manifest is refused, not reported as clean" "$TMPD/empty" "no package.json, requirements.txt or pyproject.toml" \
  clients --root "$TMPD/empty"
refused "clients: a service root outside the project is refused" "$P" "not a directory under" clients --root "$P" --service-root ../..

# ================================================================== Python: turning a package on
snap "$P"
out=$(enrich client --root "$P" --name sqlite3 --bootstrap tracing.py --dry-run); rc=$?
check "client: --dry-run prints both diffs, exits 1, writes nothing" \
  '[ "$rc" -eq 1 ] && echo "$out" | grep -q "^+++ b/requirements.txt" && echo "$out" | grep -q "^+++ b/tracing.py" && same "$P"'
check "client: the requirement takes the version the other instrumentation package is pinned to" \
  'echo "$out" | grep -q "^+opentelemetry-instrumentation-sqlite3>=0.66b2$"'
out=$(enrich client --root "$P" --name sqlite3 --bootstrap tracing.py); rc=$?
check "client: applies (exit 0)" '[ "$rc" -eq 0 ] && echo "$out" | grep -q "^OK: turned on opentelemetry-instrumentation-sqlite3"'
check "client: both files only gained lines, inside one begin and one end marker each" \
  'for f in tracing.py requirements.txt; do [ "$(grep -c "enrich begin client-sqlite3" "$P/$f")" = 1 ] && [ "$(grep -c "enrich end client-sqlite3" "$P/$f")" = 1 ] && [ "$(diff "$TMPD/py-orig/$f" "$P/$f" | grep -c "^<")" = 0 ] || exit 1; done'
check "client: the bootstrap still compiles, and the block comes after the providers are set" \
  'python3 -m py_compile "$P/tracing.py" && [ "$(grep -n "set_tracer_provider" "$P/tracing.py" | tail -1 | cut -d: -f1)" -lt "$(grep -n "SQLite3Instrumentor().instrument()" "$P/tracing.py" | cut -d: -f1)" ]'
rm -rf "$P/__pycache__"
check "client: list shows the block in both files" '[ "$(enrich list --root "$P" | grep -c "client-sqlite3")" = 2 ]'
check "client: the report now reads enabled" '[ "$(status "$P" sqlite3)" = enabled ]'
refused "client: a second run is refused" "$P" "Nothing to add" client --root "$P" --name sqlite3 --bootstrap tracing.py
# The enable block, run with no package installed: the service must still start, and say so.
warn=$(cd "$TMPD" && python3 - "$P/tracing.py" <<'PY' 2>&1
import re, sys
block = re.search(r"# otel-as-code: enrich begin client-sqlite3\n(.*?)# otel-as-code: enrich end", open(sys.argv[1]).read(), re.S).group(1)
import builtins
real = builtins.__import__
def no_otel(name, *a, **k):
    if name.startswith("opentelemetry"):
        raise ImportError(name)
    return real(name, *a, **k)
builtins.__import__ = no_otel
exec(block)
print("started")
PY
)
check "client: with the package missing the block warns and the service still starts" \
  'echo "$warn" | grep -q "opentelemetry-instrumentation-sqlite3 is not installed" && echo "$warn" | grep -q "^started$"'
# /otel-instrument regenerating the bootstrap drops the block; the requirement is still there.
cp "$GOLDEN_PY/tracing.py" "$P/tracing.py"
check "client: after the bootstrap is regenerated the report says turn-on, not enabled" '[ "$(status "$P" sqlite3)" = turn-on ]'
out=$(enrich client --root "$P" --name sqlite3 --bootstrap tracing.py)
check "client: re-applying then adds the block only, not a second requirement" \
  '! echo "$out" | grep -q "requirements.txt" && [ "$(grep -c "opentelemetry-instrumentation-sqlite3" "$P/requirements.txt")" = 1 ] && [ "$(status "$P" sqlite3)" = enabled ]'
check "client: remove --id takes the block out of both files, byte for byte" \
  'enrich remove --root "$P" --id client-sqlite3 >/dev/null && diff -r "$TMPD/py-orig" "$P" >/dev/null'
refused "client: a client the service does not use is refused" "$P" "not a client this service uses" \
  client --root "$P" --name redis --bootstrap tracing.py
refused "client: a client the table does not know is refused" "$P" "not a client this service uses" \
  client --root "$P" --name duckdb --bootstrap tracing.py
printf 'import sqlite3\n' > "$P/own.py"
refused "client: a bootstrap otel-as-code did not generate is not edited, and the lines to add are given" "$P" \
  "SQLite3Instrumentor().instrument()" client --root "$P" --name sqlite3 --bootstrap own.py
rm "$P/own.py"
cp "$GOLDEN_PY/tracing.py" "$TMPD/many/tracing.py"
refused "client: a driver under SQLAlchemy is refused with the reason" "$TMPD/many" "two spans per query" \
  client --root "$TMPD/many" --name psycopg2 --bootstrap tracing.py
cp "$GOLDEN_PY/tracing.py" "$TMPD/pp/tracing.py"
out=$(enrich client --root "$TMPD/pp" --name asyncpg --bootstrap tracing.py --dry-run)
check "client: with pyproject.toml the dependency is a line to add, not an edit to the file" \
  'echo "$out" | grep -q "^dependency: add \"opentelemetry-instrumentation-asyncpg\" to the dependencies in pyproject.toml" && ! echo "$out" | grep -q "b/pyproject.toml"'
mkdir -p "$TMPD/nopin"; cp "$GOLDEN_PY/tracing.py" "$TMPD/nopin/"; printf 'redis\n' > "$TMPD/nopin/requirements.txt"
out=$(enrich client --root "$TMPD/nopin" --name redis --bootstrap tracing.py --dry-run)
check "client: with no pin to copy, the requirement is unpinned and a note says so" \
  'echo "$out" | grep -q "^+opentelemetry-instrumentation-redis$" && echo "$out" | grep -q "^note: no other opentelemetry-instrumentation package is pinned"'
printf 'redis' > "$TMPD/nopin/requirements.txt"; cp "$TMPD/nopin/requirements.txt" "$TMPD/nopin.req"
enrich client --root "$TMPD/nopin" --name redis --bootstrap tracing.py >/dev/null
check "client: a requirements file with no final newline is restored exactly on removal" \
  'enrich remove --root "$TMPD/nopin" >/dev/null && cmp -s "$TMPD/nopin/requirements.txt" "$TMPD/nopin.req"'
refused "client: Node.js has nothing to turn on" "$ROOT/tests/enrich/node-clients" "already loads every package" \
  client --root "$ROOT/tests/enrich/node-clients" --name pg --bootstrap index.js

# ================================================================== Node.js: the report
N="$TMPD/node"; mkdir -p "$N"
cp -R tests/enrich/node-clients/. "$N/"; cp "$GOLDEN_JS/tracing.js" "$N/"
check "node: with no node_modules, bundle coverage is 'not checked', never 'covered'" \
  '[ "$(status "$N" pg --bootstrap tracing.js)" = not-checked ]'
check "node: with no bootstrap given, coverage is 'not checked'" '[ "$(status "$N" pg)" = not-checked ]'
mkdir -p "$N/node_modules/@opentelemetry/instrumentation-pg"
printf '{"name":"@opentelemetry/instrumentation-pg","version":"0.99.0"}' > "$N/node_modules/@opentelemetry/instrumentation-pg/package.json"
check "node: covered once the package is in node_modules and the bootstrap loads the bundle" \
  '[ "$(status "$N" pg --bootstrap tracing.js)" = covered ] && enrich clients --root "$N" --bootstrap tracing.js | grep -q "instrumentation-pg 0.99.0 is installed"'
sed "s|'@opentelemetry/instrumentation-fs': { enabled: false },|'@opentelemetry/instrumentation-fs': { enabled: false },\n      '@opentelemetry/instrumentation-pg': { enabled: false },|" "$N/tracing.js" > "$N/tracing.off.js"
check "node: a package the bootstrap turns off is reported as disabled" '[ "$(status "$N" pg --bootstrap tracing.off.js)" = disabled ]'
rm "$N/tracing.off.js"
check "node: a built-in client with no package is found by its import and offered a span" \
  '[ "$(status "$N" node:sqlite --bootstrap tracing.js)" = wrap ]'
mkdir -p "$TMPD/node2"
printf '{"dependencies":{"@prisma/client":"^6","better-sqlite3":"^11","kafkajs":"^2"},"devDependencies":{"mysql2":"^3"}}' > "$TMPD/node2/package.json"
check "node: a client with its own package is 'manual'; one with none is 'wrap'; devDependencies are not clients" \
  '[ "$(status "$TMPD/node2" @prisma/client)" = manual ] && [ "$(status "$TMPD/node2" better-sqlite3)" = wrap ] && [ "$(status "$TMPD/node2" mysql2)" = absent ] && [ "$(status "$TMPD/node2" kafkajs)" = not-checked ]'

# ================================================================== span --client
SPAN=(--root "$N" --file lib/store.js --function findItem --span-name store.findItem --tracer-name enrich-catalog)
refused "span --client: a client the bundle covers is refused (it would be the second span)" "$N" "two client spans per call" \
  span "${SPAN[@]}" --client pg
refused "span --client: a client with its own package is refused too" "$N" "@prisma/instrumentation" span "${SPAN[@]}" --client @prisma/client
refused "span --client: an unknown client needs --signal and --system" "$N" "not checked" span "${SPAN[@]}" --client duckdb
refused "span --client: --system must be a plain lowercase name" "$N" "lowercase system name" \
  span "${SPAN[@]}" --client duckdb --signal db --system "x', evil: '1"
refused "span --client: a queue needs --kind producer or consumer" "$N" "--kind producer" \
  span "${SPAN[@]}" --client nats --signal messaging --system nats
refused "span --client: --kind on a database call is refused" "$N" "drop --kind" span "${SPAN[@]}" --client node:sqlite --kind producer
refused "span: --system without --client is refused" "$N" "pass --client" span "${SPAN[@]}" --system sqlite
refused "span: an id in the reserved client- namespace is refused" "$N" "reserved" span "${SPAN[@]}" --id client-x
cp "$N/lib/store.js" "$TMPD/store.orig.js"
out=$(enrich span "${SPAN[@]}" --client node:sqlite); rc=$?
check "span --client node: applies, as a CLIENT span with db.system.name and nothing else" \
  '[ "$rc" -eq 0 ] && grep -qF "startActiveSpan('"'"'store.findItem'"'"', { kind: 2 /* SpanKind.CLIENT */, attributes: { '"'"'db.system.name'"'"': '"'"'sqlite'"'"' } }, (otelSpan) => { try {" "$N/lib/store.js"'
# Run it against a stub API that records what the span was started with.
mkdir -p "$N/node_modules/@opentelemetry/api"
cat > "$N/node_modules/@opentelemetry/api/index.js" <<'JS'
const spans = [];
module.exports = {
  SpanStatusCode: { ERROR: 2 }, spans,
  trace: { getTracer: () => ({ startActiveSpan: (name, opts, fn) => {
    const s = { name, kind: opts.kind, attributes: opts.attributes, ended: false,
      setStatus() {}, recordException() {}, end() { this.ended = true; } };
    spans.push(s);
    return fn(s);
  } }) },
};
JS
run=$(cd "$N" && node -e '
const { spans } = require("@opentelemetry/api");
const store = require("./lib/store");
const a = store.findItem(1), b = store.findItem(9);
console.log(JSON.stringify({ a, b, spans }));' 2>/dev/null)
check "span --client node: findItem returns what it did, and each call starts and ends one client span" \
  '[ "$run" = "{\"a\":{\"id\":1,\"name\":\"kettle\"},\"b\":null,\"spans\":[{\"name\":\"store.findItem\",\"kind\":2,\"attributes\":{\"db.system.name\":\"sqlite\"},\"ended\":true},{\"name\":\"store.findItem\",\"kind\":2,\"attributes\":{\"db.system.name\":\"sqlite\"},\"ended\":true}]}" ]'
check "span --client node: removal restores the file byte for byte" \
  'enrich remove --root "$N" --file lib/store.js >/dev/null && cmp -s "$N/lib/store.js" "$TMPD/store.orig.js"'
out=$(enrich span "${SPAN[@]}" --client nats --signal messaging --system nats --kind producer --dry-run)
check "span --client node: a queue producer is kind PRODUCER with messaging.system, and the unchecked client is noted" \
  'echo "$out" | grep -qF "{ kind: 3 /* SpanKind.PRODUCER */, attributes: { '"'"'messaging.system'"'"': '"'"'nats'"'"' } }" && echo "$out" | grep -q "^note: .nats. is not in the coverage table"'

Q="$TMPD/pyspan"; mkdir -p "$Q"
printf 'import duckdb\n\n\ndef top_items(limit):\n    return duckdb.sql("select 1").fetchall()[:limit]\n' > "$Q/report.py"
refused "span --client python: a client a package covers is refused, by distribution name too" "$Q" "opentelemetry-instrumentation-psycopg2" \
  span --root "$Q" --file report.py --function top_items --span-name report.top_items --tracer-name t --client psycopg2-binary
refused "span --client python: the standard-library client is refused the same way" "$Q" "opentelemetry-instrumentation-sqlite3" \
  span --root "$Q" --file report.py --function top_items --span-name report.top_items --tracer-name t --client sqlite3
enrich span --root "$Q" --file report.py --function top_items --span-name report.top_items --tracer-name t \
  --client duckdb --signal db --system duckdb >/dev/null
check "span --client python: the decorator asks for a CLIENT span with db.system.name" \
  'grep -qF "@_otel_tracer.start_as_current_span(\"report.top_items\", kind=_otel_trace.SpanKind.CLIENT, attributes={\"db.system.name\": \"duckdb\"})" "$Q/report.py"'
mkdir -p "$Q/opentelemetry" "$Q/duckdb"
cat > "$Q/opentelemetry/trace.py" <<'PY'
import functools
SPANS = []
class SpanKind:
    CLIENT, PRODUCER, CONSUMER = "CLIENT", "PRODUCER", "CONSUMER"
class _Tracer:
    def start_as_current_span(self, name, kind=None, attributes=None):
        def deco(fn):
            @functools.wraps(fn)
            def wrapper(*a, **k):
                SPANS.append([name, kind, attributes])
                return fn(*a, **k)
            return wrapper
        return deco
def get_tracer(name):
    return _Tracer()
PY
: > "$Q/opentelemetry/__init__.py"
printf 'class _R:\n    def fetchall(self):\n        return [(1,), (2,), (3,)]\ndef sql(q):\n    return _R()\n' > "$Q/duckdb/__init__.py"
pyrun=$(cd "$Q" && python3 -c "
import json, report
from opentelemetry.trace import SPANS
print(json.dumps([report.top_items(2), SPANS]))" 2>&1)
check "span --client python: the function returns what it did and one client span is started per call" \
  '[ "$pyrun" = "[[[1], [2]], [[\"report.top_items\", \"CLIENT\", {\"db.system.name\": \"duckdb\"}]]]" ]'

echo
echo "enrich-clients: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
