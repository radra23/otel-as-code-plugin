#!/usr/bin/env bash
# tests/telemetry-test.test.sh: offline tests of scripts/telemetry_test.py, which renders
# /otel-test's telemetry test from a spec. The rendered files are compared with the goldens and
# parsed; every value that reaches the generated code is shown to be checked first. No network
# (tests/e2e/telemetry-test.sh RUNS the generated tests against real apps). Needs node.
set -uo pipefail
cd "$(dirname "$0")/.."
ROOT=$PWD
pass=0; fail=0
check() { if eval "$2"; then echo "PASS: $1"; pass=$((pass+1)); else echo "FAIL: $1"; fail=$((fail+1)); fi; }
tt() { python3 "$ROOT/scripts/telemetry_test.py" "$@"; }
TMPD=$(mktemp -d); trap 'rm -rf "$TMPD"' EXIT
N="$TMPD/node"; P="$TMPD/py"
mkdir -p "$N" "$P"
cp -R tests/enrich/node-app/. "$N/"
cp fixtures/python-greenfield/app.py "$P/"; printf 'from app import app\n' > "$P/main.py"
NSPEC=tests/telemetry-test/node.spec.json; PSPEC=tests/telemetry-test/python.spec.json
snap() { (cd "$1" && find . -type f -exec shasum {} + | sort) > "$TMPD/snap"; }
same() { (cd "$1" && find . -type f -exec shasum {} + | sort) | cmp -s - "$TMPD/snap"; }
# spec_with <base spec> <python expression changing `s`>: a changed copy of a spec, on stdout.
spec_with() { python3 -c 'import json, sys
s = json.load(open(sys.argv[1]))
exec(sys.argv[2])
print(json.dumps(s))' "$1" "$2"; }
# refused <name> <dir> <base spec> <change> <expected words>: exit 2, one REFUSED line, nothing written.
refused() {
  local name="$1" dir="$2" base="$3" change="$4" words="$5" msg rc
  snap "$dir"
  msg=$(spec_with "$base" "$change" | tt render --root "$dir" --spec - 2>&1); rc=$?
  check "$name" '[ "$rc" -eq 2 ] && echo "$msg" | grep -q "^REFUSED: " && echo "$msg" | grep -qi -- "$words" && same "$dir"'
}

# ================================================================== rendering
check "the file names are the ones hooks/otel-paths.sh guards" \
  '[ "$(. hooks/otel-paths.sh; otel_test_globs | sort | tr "\n" " ")" = "$(python3 -c "import sys; sys.path.insert(0, \"scripts\"); import telemetry_test as t; print(\" \".join(sorted(t.FILE_NAMES.values())), end=\" \")")" ]'
snap "$N"
out=$(tt render --root "$N" --spec "$NSPEC" --dry-run); rc=$?
check "node: --dry-run prints the file as a diff, exits 1, writes nothing" \
  '[ "$rc" -eq 1 ] && echo "$out" | grep -q "^+++ b/otel.test.cjs" && echo "$out" | grep -q "^dry run: would write otel.test.cjs" && same "$N"'
out=$(tt render --root "$N" --spec "$NSPEC"); rc=$?
check "node: render writes otel.test.cjs and says what it asserts" \
  '[ "$rc" -eq 0 ] && echo "$out" | grep -q "^OK: wrote otel.test.cjs (4 span(s), 2 metric(s) asserted)"'
check "node: the rendered file equals the golden" 'cmp -s "$N/otel.test.cjs" tests/snapshots/telemetry-test/otel.test.cjs'
check "node: the golden parses" 'node --check tests/snapshots/telemetry-test/otel.test.cjs'
check "node: it carries the ownership marker and the plugin version" \
  'head -1 "$N/otel.test.cjs" | grep -q "generated by otel-as-code v$(python3 -c "import json; print(json.load(open(\".claude-plugin/plugin.json\"))[\"version\"])") (/otel-test)"'
check "node: the header says in plain words what it protects, how it works and how to run it" \
  'grep -q "^// What this protects: POST /checkout" "$N/otel.test.cjs" && grep -q "^// How it works:" "$N/otel.test.cjs" && grep -q "^// Run it: node --test otel.test.cjs" "$N/otel.test.cjs"'
check "node: what the request cannot reach is listed, with the reason" \
  'grep -q "^//   - orders.describe: no route calls describe()" "$N/otel.test.cjs"'
check "node: a second render with nothing changed is a no-op" \
  'out=$(tt render --root "$N" --spec "$NSPEC") && echo "$out" | grep -q "already up to date"'
snap "$N"
msg=$(spec_with "$NSPEC" 's["spans"].remove("pricing.total")' | tt render --root "$N" --spec - 2>&1); rc=$?
check "node: regenerating a generated test with different content needs --force" \
  '[ "$rc" -eq 2 ] && echo "$msg" | grep -q "pass --force" && same "$N"'
check "node: --force regenerates it" \
  'spec_with "$NSPEC" "s[\"spans\"].remove(\"pricing.total\")" | tt render --root "$N" --spec - --force >/dev/null && ! grep -q "pricing.total" "$N/otel.test.cjs"'
printf '// my own test\n' > "$N/otel.test.cjs"
snap "$N"
msg=$(tt render --root "$N" --spec "$NSPEC" --force 2>&1); rc=$?
check "node: a hand-written file of that name is never overwritten, even with --force" \
  '[ "$rc" -eq 2 ] && echo "$msg" | grep -q "was not generated by otel-as-code" && same "$N"'
rm "$N/otel.test.cjs"
check "path: prints where the test goes" '[ "$(tt path --root "$N" --spec "$NSPEC")" = "otel.test.cjs" ]'

tt render --root "$P" --spec "$PSPEC" >/dev/null
check "python: the rendered file equals the golden" 'cmp -s "$P/test_otel.py" tests/snapshots/telemetry-test/test_otel.py'
check "python: the golden compiles" 'python3 -m py_compile tests/snapshots/telemetry-test/test_otel.py'
find tests/snapshots/telemetry-test -name __pycache__ -type d -exec rm -rf {} + 2>/dev/null
check "python: the header says how to run it and why in its own process" \
  'grep -q "^# Run it: python -m unittest test_otel" "$P/test_otel.py" && grep -q "^# Run it in its own process" "$P/test_otel.py"'
rm "$P/test_otel.py"

# ================================================================== the request body is data, never code
tricky='s["request"]["json"] = {"note": "\"); process.exit(0); (\"", "py": "\x27\x27\x27 + __import__(\"os\").system(\"true\") + \x27\x27\x27", "n": None, "ok": True}'
spec_with "$NSPEC" "$tricky" | tt render --root "$N" --spec - >/dev/null
check "node: a request body full of quotes still parses and round-trips as data" \
  'node --check "$N/otel.test.cjs" && node -e "
const src = require(\"fs\").readFileSync(process.argv[1], \"utf8\");
const req = JSON.parse(src.match(/^const REQUEST = (.*);\$/m)[1]);
process.exit(req.json.note === \"\\\"); process.exit(0); (\\\"\" && req.json.n === null && req.json.ok === true ? 0 : 1);" "$N/otel.test.cjs"'
rm "$N/otel.test.cjs"
spec_with "$PSPEC" "$tricky" | tt render --root "$P" --spec - >/dev/null
check "python: the same body compiles and round-trips as data (null and true included)" \
  'python3 - "$P/test_otel.py" <<PY
import ast, json, sys
tree = ast.parse(open(sys.argv[1]).read())
call = next(n.value for n in tree.body if isinstance(n, ast.Assign) and n.targets[0].id == "REQUEST")
req = json.loads(ast.literal_eval(call.args[0]))
ok = req["json"]["n"] is None and req["json"]["ok"] is True and "__import__" in req["json"]["py"]
sys.exit(0 if ok else 1)
PY'
rm "$P/test_otel.py"
spec_with "$NSPEC" 's["notCovered"] = [{"name": "x */ process.exit(1) /*", "reason": "line one\nprocess.exit(1)"}]' | tt render --root "$N" --spec - >/dev/null
check "node: a notCovered entry cannot break out of its comment line" \
  'node --check "$N/otel.test.cjs" && [ "$(grep -c "^process.exit" "$N/otel.test.cjs")" = 0 ] && grep -q "^//   - x \* / process.exit(1) /\*: line one process.exit(1)$" "$N/otel.test.cjs"'
rm "$N/otel.test.cjs"

# ================================================================== refusals
refused "spec: an unsupported language is refused" "$N" "$NSPEC" 's["language"] = "go"' "nodejs or python"
refused "spec: a start argument with shell characters is refused" "$N" "$NSPEC" 's["start"] = ["index.js; rm -rf /"]' "list of arguments"
refused "spec: a start script that does not exist is refused" "$N" "$NSPEC" 's["start"] = ["-r", "./tracing.js", "nope.js"]; del s["startScript"]' "script that exists"
refused "spec: startScript must match the package.json script" "$N" "$NSPEC" 's["start"] = ["index.js"]' "make .start. match it"
refused "spec: a port variable that is not a variable name is refused" "$N" "$NSPEC" 's["portEnv"] = "PORT; x"' "environment variable name"
refused "spec: a path with a quote is refused" "$N" "$NSPEC" 's["request"]["path"] = "/a\x27+b"' "URL path"
refused "spec: an absolute URL instead of a path is refused" "$N" "$NSPEC" 's["request"]["path"] = "http://example.com/x"' "URL path"
refused "spec: an unknown method is refused" "$N" "$NSPEC" 's["request"]["method"] = "TRACE"' "request.method"
refused "spec: a body on a GET is refused" "$N" "$NSPEC" 's["request"]["method"] = "GET"' "carries no"
refused "spec: a status that is not a status is refused" "$N" "$NSPEC" 's["request"]["expectStatus"] = "200"' "status code"
refused "spec: a span name with a quote is refused" "$N" "$NSPEC" 's["spans"] = ["a\"b"]' "plain span name"
refused "spec: a metric name with a space is refused" "$N" "$NSPEC" 's["metrics"] = ["a b"]' "plain metric name"
refused "spec: a server span with a backtick is refused" "$N" "$NSPEC" 's["serverSpan"] = "POST /x`id`"' "request span.s name"
# Next.js names a dynamic route with brackets and a catch-all with `[...name]` (#318).
for route in 'GET /api/services/[id]' 'GET /api/auth/[...nextauth]'; do
  snap "$N"
  out=$(spec_with "$NSPEC" "s['serverSpan'] = '$route'" | tt render --root "$N" --spec - --dry-run 2>&1); rc=$?
  check "spec: the Next.js route \"$route\" is accepted" \
    '[ "$rc" -eq 1 ] && ! echo "$out" | grep -q "^REFUSED" && echo "$out" | grep -qF "serverSpan: \"$route\"" && same "$N"'
done
refused "spec: brackets do not open a way to inject code" "$N" "$NSPEC" 's["serverSpan"] = "GET /x[`id`]"' "request span.s name"
refused "spec: the server span repeated under spans is refused" "$N" "$NSPEC" 's["spans"].append("POST /checkout")' "repeats"
refused "spec: a service root outside the project is refused" "$N" "$NSPEC" 's["serviceRoot"] = "../.."; del s["startScript"]' "not a directory under"
refused "spec: python needs module:attribute" "$P" "$PSPEC" 's["app"] = "main.app()"' "module:attribute"
refused "spec: python needs asgi or wsgi" "$P" "$PSPEC" 's["interface"] = "cgi"' "asgi or wsgi"
refused "spec: the python app module must be in the service" "$P" "$PSPEC" 's["app"] = "nowhere:app"' "is not under"
refused "spec: a bootstrap name that is not a module name is refused" "$P" "$PSPEC" 's["bootstrap"] = "tracing; import os"' "module name"
# A value that passes a `^...$` check with a newline on the end would break out of the comment it
# is written into and become a line of code.
refused "spec: a start argument ending in a newline is refused" "$N" "$NSPEC" 's["start"] = ["-r", "./tracing.js", "index.js\nprocess.exit(0)//"]; del s["startScript"]' "list of arguments"
refused "spec: a start argument that is only a trailing newline off is refused" "$N" "$NSPEC" 's["start"][2] = "index.js\n"; del s["startScript"]' "list of arguments"
refused "spec: a service name ending in a newline is refused" "$N" "$NSPEC" 's["serviceName"] = "orders\n"' "plain name"
refused "spec: a server span ending in a newline is refused" "$N" "$NSPEC" 's["serverSpan"] = "POST /checkout\n"' "request span.s name"
refused "spec: a path ending in a newline is refused" "$N" "$NSPEC" 's["request"]["path"] = "/checkout\n"' "URL path"
refused "spec: a span name ending in a newline is refused" "$N" "$NSPEC" 's["spans"] = ["orders.checkout\n"]' "plain span name"
refused "spec: a python app ending in a newline is refused" "$P" "$PSPEC" 's["app"] = "main:app\n"' "module:attribute"
# Text in the request body that looks like one of the template's own placeholders must stay text:
# filled in a second pass it would be replaced by code-shaped JSON inside a string literal.
spec_with "$NSPEC" 's["request"]["json"] = {"a": "__SPANS__", "b": "__START__ __METRICS__ __SERVER_SPAN__"}' | tt render --root "$N" --spec - >/dev/null
check "node: placeholder-shaped text in the request body is left as it is" \
  'node --check "$N/otel.test.cjs" && grep -qF "\"a\": \"__SPANS__\"" "$N/otel.test.cjs" && grep -qF "__START__ __METRICS__ __SERVER_SPAN__" "$N/otel.test.cjs"'
rm -f "$N/otel.test.cjs"
spec_with "$PSPEC" 's["request"]["json"] = {"a": "__SPANS__ __APP__ __BOOTSTRAP__"}' | tt render --root "$P" --spec - >/dev/null
check "python: placeholder-shaped text in the request body is left as it is" \
  'python3 -m py_compile "$P/test_otel.py" && grep -qF "__SPANS__ __APP__ __BOOTSTRAP__" "$P/test_otel.py"'
rm -rf "$P/test_otel.py" "$P/__pycache__"
check "no placeholder is left unfilled in either golden" '! grep -nE "__[A-Z_]+__" tests/snapshots/telemetry-test/otel.test.cjs tests/snapshots/telemetry-test/test_otel.py | grep -v "__name__\|__file__\|__dirname"'

snap "$N"
msg=$(printf '{not json' | tt render --root "$N" --spec - 2>&1); rc=$?
check "spec: text that is not JSON is refused in one line" '[ "$rc" -eq 2 ] && echo "$msg" | grep -q "^REFUSED: the spec is not valid JSON" && same "$N"'
ln -s "$TMPD/elsewhere.cjs" "$N/otel.test.cjs"
msg=$(tt render --root "$N" --spec "$NSPEC" 2>&1); rc=$?
check "a symbolic link in the test's place is not written through" '[ "$rc" -eq 2 ] && echo "$msg" | grep -q "symbolic link" && [ ! -e "$TMPD/elsewhere.cjs" ]'
rm "$N/otel.test.cjs"

echo
echo "telemetry-test: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
