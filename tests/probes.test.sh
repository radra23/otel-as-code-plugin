#!/usr/bin/env bash
# tests/probes.test.sh: offline tests of scripts/probes.py (apply and remove /otel-why's probe
# spans) and of the two probe helper templates. Real files in a temp project; no network, no SDK
# (the helpers run against a stub OpenTelemetry API that records what they do).
set -uo pipefail
cd "$(dirname "$0")/.."
pass=0; fail=0
check() { if eval "$2"; then echo "PASS: $1"; pass=$((pass+1)); else echo "FAIL: $1"; fail=$((fail+1)); fi; }
PR="python3 $(pwd)/scripts/probes.py"
VERSION=$(python3 -c "import json; print(json.load(open('.claude-plugin/plugin.json'))['version'])")
TMPD=$(mktemp -d); trap 'rm -rf "$TMPD"' EXIT

fresh() { rm -rf "$TMPD/p"; mkdir -p "$TMPD/p"; cp -R tests/why/app/. "$TMPD/p/"; cp -R tests/why/app "$TMPD/orig"; }
rm -rf "$TMPD/orig"; fresh
P="$TMPD/p"

# --- helper ---
check "helper writes otel-probe.js with the ownership marker and this version" \
  '$PR helper --lang nodejs --dir "$P" --root "$P" >/dev/null && head -1 "$P/otel-probe.js" | grep -q "generated by otel-as-code v$VERSION (/otel-why)"'
check "helper uses the otel-as-code.probe tracer name, the trace-side marker" \
  'grep -q "getTracer(.otel-as-code.probe.)" "$P/otel-probe.js"'
check "helper is idempotent for the file it wrote" '$PR helper --lang nodejs --dir "$P" --root "$P" | grep -q "already in place"'
echo "// mine" > "$P/otel_probe.py"
check "helper refuses to overwrite a file it did not write" \
  '! $PR helper --lang python --dir "$P" --root "$P" 2>/dev/null && [ "$(cat "$P/otel_probe.py")" = "// mine" ]'
rm "$P/otel_probe.py"
check "helper refuses a directory outside the project" '! $PR helper --lang nodejs --dir "$TMPD" --root "$P" 2>/dev/null'

# --- apply: every refusal writes nothing ---
spec() { python3 -c "import json,sys; print(json.dumps(json.loads(sys.argv[1])))" "$1" > "$TMPD/spec.json"; }
snap() { (cd "$P" && find . -type f -not -path "./.claude/*" -exec shasum {} + | sort) > "$TMPD/snap"; }
same() { (cd "$P" && find . -type f -not -path "./.claude/*" -exec shasum {} + | sort) | cmp -s - "$TMPD/snap"; }
snap
spec '[{"id":"a","file":"lib/db.js","find":"nowhere in the file","replace":"// otel-as-code: probe begin a\nx\n// otel-as-code: probe end a\n"}]'
check "apply refuses a find that does not occur, and writes nothing" '! $PR apply --spec "$TMPD/spec.json" --root "$P" 2>/dev/null && same'
spec '[{"id":"a","file":"lib/db.js","find":"sleep","replace":"// otel-as-code: probe begin a\nx\n// otel-as-code: probe end a\n"}]'
check "apply refuses a find that occurs more than once" \
  'msg=$($PR apply --spec "$TMPD/spec.json" --root "$P" 2>&1); [ $? -ne 0 ] && echo "$msg" | grep -q "occurs [0-9]* times" && same'
spec '[{"id":"a","file":"lib/db.js","find":"await sleep(ROUND_TRIP_MS);","replace":"await sleep(1);"}]'
check "apply refuses a replace without its begin and end markers" '! $PR apply --spec "$TMPD/spec.json" --root "$P" 2>/dev/null && same'
spec '[{"id":"a","file":"lib/db.py","find":"x","replace":"// otel-as-code: probe begin a\nx\n// otel-as-code: probe end a\n"}]'
check "apply refuses a file that is not there" '! $PR apply --spec "$TMPD/spec.json" --root "$P" 2>/dev/null && same'
spec '[{"id":"ok","file":"lib/db.js","find":"await sleep(ROUND_TRIP_MS);\n","replace":"// otel-as-code: probe begin ok\nawait sleep(ROUND_TRIP_MS);\n// otel-as-code: probe end ok\n"},{"id":"bad","file":"lib/carts.js","find":"missing","replace":"// otel-as-code: probe begin bad\n// otel-as-code: probe end bad\n"}]'
check "one bad probe in a spec writes none of them" '! $PR apply --spec "$TMPD/spec.json" --root "$P" 2>/dev/null && same'
spec '[{"id":"a","file":"../escape.js","find":"x","replace":"// otel-as-code: probe begin a\n// otel-as-code: probe end a\n"}]'
check "apply refuses a file outside the project" '! $PR apply --spec "$TMPD/spec.json" --root "$P" 2>/dev/null && same'
spec '[{"id":"py","file":"x.py","find":"y = 1\n","replace":"// otel-as-code: probe begin py\ny = 1\n// otel-as-code: probe end py\n"}]'
echo "y = 1" > "$P/x.py"; snap
check "a Python file needs # markers, not //" '! $PR apply --spec "$TMPD/spec.json" --root "$P" 2>/dev/null && same'
rm "$P/x.py"

# --- apply, then remove ---
check "the fixture's five probes apply" '$PR apply --spec tests/why/probes.json --root "$P" | grep -q "applied 5 probe(s) in 2 file(s)"'
check "applied probes carry the markers in the files" '[ "$(grep -c "otel-as-code: probe begin" "$P/lib/orders.js")" = 3 ]'
check "applying the same ids again is refused" '! $PR apply --spec tests/why/probes.json --root "$P" 2>/dev/null'
check "list names the helper and every probe" '[ "$($PR list --root "$P" | wc -l | tr -d " ")" = 6 ]'
check "remove --dry-run changes nothing and exits 1" \
  'snap; out=$($PR remove --dry-run --root "$P"); rc=$?; [ $rc -eq 1 ] && echo "$out" | grep -q "would restore: lib/orders.js" && same'

# The user edits the probed file outside the probe blocks: removal keeps that edit.
printf '\n// a later edit by the user\n' >> "$P/lib/orders.js"
check "remove restores every file and deletes the helper" '$PR remove --root "$P" | grep -q "removed 5 probe(s) and 1 helper"'
check "the user's own edit outside the probes survives removal" 'tail -1 "$P/lib/orders.js" | grep -q "a later edit by the user"'
check "apart from that edit, the files are byte for byte the originals" \
  'head -n "$(wc -l < "$TMPD/orig/lib/orders.js")" "$P/lib/orders.js" | cmp -s - "$TMPD/orig/lib/orders.js" && cmp -s "$P/lib/inventory.js" "$TMPD/orig/lib/inventory.js" && [ ! -e "$P/otel-probe.js" ]'
check "the manifest is gone, and an otherwise empty .claude/ with it" '[ ! -e "$P/.claude" ]'
check "remove with nothing recorded is a no-op" '$PR remove --root "$P" | grep -q "nothing to remove"'

# Refusals on removal: an edited probe block or helper is not thrown away.
fresh; P="$TMPD/p"; mkdir -p "$P/.claude"; echo '{}' > "$P/.claude/otel-context.json"
$PR helper --lang nodejs --dir "$P" --root "$P" >/dev/null; $PR apply --spec tests/why/probes.json --root "$P" >/dev/null
sed -i.bak 's/probe(.db.getProduct., () => db.getProduct(item.sku))/probe("db.getProduct", () => db.getProduct(item.sku, true))/' "$P/lib/inventory.js"; rm -f "$P/lib/inventory.js.bak"
snap
check "remove refuses when a probe block was edited, and writes nothing" \
  'msg=$($PR remove --root "$P" 2>&1); [ $? -ne 0 ] && echo "$msg" | grep -q "probe get-product in lib/inventory.js was edited" && same && [ -e "$P/otel-probe.js" ]'
fresh; P="$TMPD/p"; mkdir -p "$P/.claude"; echo '{}' > "$P/.claude/otel-context.json"
$PR helper --lang nodejs --dir "$P" --root "$P" >/dev/null; $PR apply --spec tests/why/probes.json --root "$P" >/dev/null
echo "// tweaked" >> "$P/otel-probe.js"; snap
check "remove refuses when the helper was edited" \
  'msg=$($PR remove --root "$P" 2>&1); [ $? -ne 0 ] && echo "$msg" | grep -q "otel-probe.js was edited" && same'
sed -i.bak '$d' "$P/otel-probe.js"; rm -f "$P/otel-probe.js.bak"
check "once the edit is undone, remove succeeds and leaves the context cache alone" \
  '$PR remove --root "$P" >/dev/null && [ -f "$P/.claude/otel-context.json" ] && [ ! -e "$P/.claude/otel-probes.json" ]'

# --- the helpers' behavior, against a stub OpenTelemetry API ---
mkdir -p "$TMPD/node/node_modules/@opentelemetry/api"
cat > "$TMPD/node/node_modules/@opentelemetry/api/index.js" <<'JS'
const spans = [];
module.exports = {
  SpanStatusCode: { ERROR: 2 },
  trace: { getTracer: (scope) => ({ startActiveSpan: (name, fn) => {
    const s = { scope, name, attrs: {}, status: null, ended: false, errors: 0,
      setAttribute(k, v) { this.attrs[k] = v; }, setStatus(x) { this.status = x.code; },
      recordException() { this.errors++; }, end() { this.ended = true; } };
    spans.push(s); return fn(s); } }) },
  _spans: spans,
};
JS
sed "s/{{VERSION}}/$VERSION/" scripts/probe-templates/otel-probe.js > "$TMPD/node/otel-probe.js"
node_out=$(cd "$TMPD/node" && node -e "
const { probe } = require('./otel-probe'); const api = require('@opentelemetry/api');
(async () => {
  const a = probe('sync', () => 41 + 1);
  const b = await probe('async', () => new Promise((r) => setTimeout(() => r('done'), 20)));
  let threw = false; try { probe('boom', () => { throw new Error('x'); }); } catch (e) { threw = e.message === 'x'; }
  let rejected = false; await probe('reject', () => Promise.reject(new Error('y'))).catch((e) => { rejected = e.message === 'y'; });
  const s = api._spans;
  console.log(JSON.stringify({ a, b, threw, rejected, scopes: [...new Set(s.map((x) => x.scope))],
    ended: s.every((x) => x.ended), cpu: s.every((x) => typeof x.attrs['otel_as_code.probe.cpu_ms'] === 'number'),
    errors: s.filter((x) => x.status === 2).map((x) => x.name) }));
})();" 2>&1)
check "node helper: returns values and promises unchanged" 'echo "$node_out" | grep -q "\"a\":42,\"b\":\"done\""'
check "node helper: rethrows sync errors and rejections, marking those spans as errors" \
  'echo "$node_out" | grep -q "\"threw\":true,\"rejected\":true" && echo "$node_out" | grep -q "\"errors\":\[\"boom\",\"reject\"\]"'
check "node helper: every span ends, under otel-as-code.probe, with a CPU figure" \
  'echo "$node_out" | grep -q "\"scopes\":\[\"otel-as-code.probe\"\],\"ended\":true,\"cpu\":true"'

mkdir -p "$TMPD/py/opentelemetry"
cat > "$TMPD/py/opentelemetry/__init__.py" <<'PYSTUB'
PYSTUB
cat > "$TMPD/py/opentelemetry/trace.py" <<'PYSTUB'
import contextlib
SPANS = []
class _Span:
    def __init__(self, scope, name): self.scope, self.name, self.attrs, self.ended = scope, name, {}, False
    def set_attribute(self, k, v): self.attrs[k] = v
class _Tracer:
    def __init__(self, scope): self.scope = scope
    @contextlib.contextmanager
    def start_as_current_span(self, name):
        s = _Span(self.scope, name); SPANS.append(s)
        try:
            yield s
        finally:
            s.ended = True
def get_tracer(scope): return _Tracer(scope)
PYSTUB
sed "s/{{VERSION}}/$VERSION/" scripts/probe-templates/otel_probe.py > "$TMPD/py/otel_probe.py"
py_out=$(cd "$TMPD/py" && python3 -c "
import asyncio, json
from otel_probe import probe
from opentelemetry.trace import SPANS
a = probe('sync', lambda x: x + 1, 41)
async def co(v):
    await asyncio.sleep(0.01); return v
b = asyncio.run(probe('async', co, 'done'))
try:
    probe('boom', lambda: 1 / 0); threw = False
except ZeroDivisionError:
    threw = True
print(json.dumps({'a': a, 'b': b, 'threw': threw, 'scopes': sorted({s.scope for s in SPANS}),
                  'ended': all(s.ended for s in SPANS), 'n': len(SPANS),
                  'cpu': all(isinstance(s.attrs.get('otel_as_code.probe.cpu_ms'), float) for s in SPANS)}))" 2>&1)
check "python helper: passes arguments and returns values, sync and async" 'echo "$py_out" | grep -q "\"a\": 42, \"b\": \"done\""'
check "python helper: exceptions propagate, every span ends with a CPU figure" \
  'echo "$py_out" | grep -q "\"threw\": true, \"scopes\": \[\"otel-as-code.probe\"\], \"ended\": true, \"n\": 3, \"cpu\": true"'

echo
echo "probes: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
