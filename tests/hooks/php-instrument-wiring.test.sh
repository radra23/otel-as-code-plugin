#!/usr/bin/env bash
# tests/hooks/php-instrument-wiring.test.sh
# Locks PHP's wiring (#117) across the scanner gate, /otel-instrument, the generator and the
# golden fixture. The golden composer.json/telemetry.php are compared to the generator's own
# template text, so a change to one without the other fails here, offline.
# Supersedes tests/hooks/php-refusal.test.sh (deleted): PHP is no longer refused, it generates.
set -uo pipefail
cd "$(dirname "$0")/../.."
source tests/hooks/lib/supported-languages.sh   # supported_languages, read by meaning (#259)
source tests/hooks/lib/maturity-status.sh      # maturity_status, read by table row (#259)
source tests/hooks/lib/step8-languages.sh       # step8_languages, read by meaning (#259)
pass=0; fail=0
check() { if eval "$2"; then echo "PASS: $1"; pass=$((pass+1)); else echo "FAIL: $1"; fail=$((fail+1)); fi; }

SCANNER="agents/repo-context-scanner.md"
CMD="commands/otel-instrument.md"
GEN="agents/instrumentation-gen.md"
MAT="skills/language-maturity/SKILL.md"
INIT="commands/otel-init.md"
GOLD="tests/snapshots/instrument/php"
FIX="fixtures/php-laravel-app"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

# Read live rather than hardcode a literal: the golden's own "generated by otel-as-code vX.Y.Z"
# line is kept current with the real plugin version by #177's dogfooding-regression check, so a
# hardcoded literal here goes stale on every release bump (as it did for 0.9.0).
REAL_VERSION=$(python3 -c "import json; print(json.load(open('.claude-plugin/plugin.json'))['version'])")

# --- scanner gate: no refusal case, framework decides placement only ---
check "scanner: php is generatorSupported:true unconditionally, no framework refusal" \
  'grep -qF "For \`php\` it is \`true\` unconditionally" "$SCANNER" \
   && grep -qF "there is no framework refusal case" "$SCANNER"'
check "scanner: brownfield exclusion is open-telemetry/* already in composer.json" \
  'grep -qF "an \`open-telemetry/sdk\` (or any \`open-telemetry/*\`) entry" "$SCANNER" \
   && grep -qF "already in \`composer.json\`" "$SCANNER"'
check "scanner: laravel/symfony are framework enum values, detected from composer.json require" \
  'grep -qF "laravel\`, \`symfony\`, \`other\`, \`unknown\`" "$SCANNER" \
   && grep -qF "laravel/framework\` entry in \`composer.json\`" "$SCANNER" \
   && grep -qF "symfony/framework-bundle\` or a bare \`symfony/symfony\`" "$SCANNER"'
check "scanner: existing-OTel detection covers open-telemetry/ in composer.json" \
  'grep -qF "open-telemetry/\` in \`composer.json\`" "$SCANNER"'
check "scanner no longer claims php is outside today's codegen" \
  '! grep -q "php.*outside today.s codegen" "$SCANNER"'

# --- command ---
check "otel-instrument lists php as supported, not v1-only" \
  'supported_languages | grep -qx php && ! grep -q "v1 will add: php" "$CMD"'
check "Step 8 puts PHP with the languages that export nowhere until configured, on OTLP/HTTP :4318" \
  'step8_languages silent "$CMD" | grep -qxF PHP && step8_languages http "$CMD" | grep -qxF PHP'
check "the golden stands down the way Step 8 says: every exporter none, then no provider" \
  'grep -qF "putenv(\$var . '"'"'='"'"' . (\$endpointSet ? '"'"'otlp'"'"' : '"'"'none'"'"'));" "$GOLD/telemetry.php" \
   && grep -qF "http://localhost:4318" "$GOLD/telemetry.php"'
check "otel-instrument documents composer validate + php -l as the PHP smoke check" \
  'grep -qF "For **PHP** the equivalent check is \`composer validate && php -l telemetry.php\`" "$CMD"'

# --- maturity ---
check "language-maturity: runtime php is in scope" \
  'grep -qE "^\| \`php\` +\| yes" "$MAT"'
check "language-maturity: PHP's table has all three core signals Stable, so none needs --experimental" \
  '[ "$(maturity_status PHP Traces "$MAT")" = Stable ] && [ "$(maturity_status PHP Metrics "$MAT")" = Stable ] \
   && [ "$(maturity_status PHP Logs "$MAT")" = Stable ]'
check "language-maturity: PHP's own SDK-default gotcha (otlp+localhost, not a no-op) is documented" \
  'grep -qiF "otlp enabled + localhost" "$MAT"'
check "PHP removed from the v1-additions stub table (it is a real section now)" \
  'grep -qF "PHP shipped (#117)" "$MAT" && ! grep -qE "^\| PHP +\| Stable +\| Stable +\| Stable" "$MAT"'

# --- generator ---
check "instrumentation-gen defines the PHP section" \
  'grep -qF "## PHP (Laravel / Symfony / framework-agnostic" "$GEN"'
check "generator states there is no framework refusal case for PHP" \
  'grep -qF "**There is no framework refusal case**" "$GEN"'
check "generator documents the none-unless-configured exporter guard and why it is needed" \
  'grep -qF "OTEL_TRACES_EXPORTER" "$GEN" && grep -qF "does NOT no-op on" "$GEN" \
   && grep -qF "http://localhost:4318" "$GEN"'
check "generator gates the Monolog logs bridge on Monolog being detected, outside Laravel" \
  'grep -qF "monolog/monolog" "$GEN" && grep -qF "for any other service with Monolog" "$GEN"'
check "generator prints the PECL extension + php.ini step as a host change it cannot make itself" \
  'grep -qiF "pecl install opentelemetry" "$GEN" \
   && grep -qiF "this plugin cannot touch the host" "$GEN"'
check "generator says how far the PHP bootstrap is runtime-verified, and what is not run" \
  'grep -qF "This file is only partly runtime-verified." "$GEN" && grep -qF "runs the metrics export." "$GEN"'
check "the bootstrap sets the propagator (OTEL_PROPAGATORS through PropagatorFactory), in the template and the golden" \
  'grep -qF "        ->withPropagator((new PropagatorFactory())->create());" "$GOLD/telemetry.php" && grep -qF "        ->withPropagator((new PropagatorFactory())->create());" "$GEN" && grep -qxF "use OpenTelemetry\SDK\Propagation\PropagatorFactory;" "$GOLD/telemetry.php"'
check "the Symfony summary puts the extension before composer update, and says why" \
  'grep -qF "followed by: \"Do step 2 first. opentelemetry-auto-symfony requires" "$GEN" && grep -qF "ext-opentelemetry, so Composer refuses this step on a machine without the extension." "$GEN"'
check "for Symfony the generator adds the two PSR implementations and names them in step 1 (else bump-after-update fails the step)" \
  'grep -qF "\`\"nyholm/psr7\": \"^1.8\"\` and \`\"symfony/http-client\"\` at the app'"'"'s own \`symfony/framework-bundle\`" "$GEN" && grep -qF "print step 1 as \`composer update '"'"'open-telemetry/*'"'"' nyholm/psr7 symfony/http-client\`" "$GEN"'
check "the route-naming caveat states what was measured per framework, not that it is unconfirmed" \
  '! grep -qF "was not independently confirmed from docs" "$GEN" && grep -qF "e.g. GET app_order_show for /orders/{id} (measured" "$GEN" && grep -qF "e.g. GET /orders/{id}" "$GEN"'
check "the e2e runs a Symfony app with a known traceparent, and requires the composer step to fail without the extension" \
  'grep -qF "symfony/skeleton symfony" tests/e2e/log-trace-ids.sh && grep -qF "traceparent: 00-\$SY_TRACE-\$SY_PARENT-01" tests/e2e/log-trace-ids.sh && grep -qF "succeeded without the extension" tests/e2e/log-trace-ids.sh'
check "the printed host step says why OTEL_PHP_AUTOLOAD_ENABLED is needed, not that it is unconfirmed" \
  '! grep -qF "deployment env — unconfirmed" "$GEN" && grep -qF "registers its hooks only through" "$GEN" && grep -qF "the SDK'"'"'s autoloader, which runs only when OTEL_PHP_AUTOLOAD_ENABLED=true." "$GEN"'
check "the golden sets OTEL_*_EXPORTER before the no-endpoint return (what keeps the autoload variable from exporting)" \
  'g=$GOLD/telemetry.php; a=$(grep -n "^    putenv(\$var" $g | cut -d: -f1); b=$(grep -n "^if (!\$endpointSet) {" $g | cut -d: -f1); [ -n "$a" ] && [ -n "$b" ] && [ "$a" -lt "$b" ]'
check "the e2e runs the Laravel auto package with the variable, and CI requires the extension" \
  'grep -qF "lv_request laravel-auto OTEL_PHP_AUTOLOAD_ENABLED=true" tests/e2e/log-trace-ids.sh && grep -qF "extensions: opentelemetry" .github/workflows/ci.yml && grep -qF "OTEL_AS_CODE_REQUIRE_PHP_EXTENSION: '"'"'1'"'"'" .github/workflows/ci.yml'

# Extract the generator's telemetry.php template and fill the placeholders with the golden's values.
awk '/^```php$/{f++; if(f==1){g=1;next}} g&&/^```$/{exit} g' "$GEN" \
  | sed -e "s/<SEMCONV_VERSION>/$(grep -oE 'SEMCONV_VERSION: [0-9.]+' skills/semconv-discipline/SKILL.md | cut -d' ' -f2)/" \
        -e "s/<PLUGIN_VERSION>/$REAL_VERSION/" \
        -e "s/getenv('OTEL_SERVICE_NAME') ?: '<SERVICE_NAME>'/getenv('OTEL_SERVICE_NAME') ?: 'billing-api'/" \
        -e "s/getenv('OTEL_SERVICE_VERSION') ?: '<SERVICE_VERSION>'/getenv('OTEL_SERVICE_VERSION') ?: '1.0.0'/" \
        -e "s/getenv('DEPLOYMENT_ENV') ?: '<DEPLOYMENT_ENV>'/getenv('DEPLOYMENT_ENV') ?: 'development'/" \
  | grep -v "service.namespace\|otherwise delete this line rather than emit a placeholder" > "$tmp/telemetry.php"
check "golden telemetry.php is the generator's template, filled in (no confirmed namespace -> line dropped)" \
  'test -s "$tmp/telemetry.php" && diff -u "$tmp/telemetry.php" "$GOLD/telemetry.php"'
check "golden telemetry.php keeps the exporter guard, provider registration, and shutdown function" \
  'grep -q "endpointSet ? .otlp. : .none." "$GOLD/telemetry.php" \
   && grep -q "withTracerProvider" "$GOLD/telemetry.php" \
   && grep -q "register_shutdown_function" "$GOLD/telemetry.php"'

# The composer.json block, verbatim from the generator: the first json fence under its heading
# (counting json fences from the top of the file found a Node.js snippet, and the package check
# below then passed on an empty list).
awk '/^### Update `composer.json`/{h=1} h&&/^```json$/{g=1;next} g&&/^```$/{exit} g' "$GEN" > "$tmp/core_block.json"
check "golden composer.json carries every core OTel package the generator's json block lists" \
  'core_pkgs=$(grep -oE "\"open-telemetry/[a-z-]+\":" "$tmp/core_block.json" | tr -d "\":"); \
   missing=0; for p in $core_pkgs; do grep -qF "\"$p\":" "$GOLD/composer.json" || missing=1; done; \
   [ -n "$core_pkgs" ] && [ "$missing" -eq 0 ]'
check "the generator's composer block loads the bootstrap through autoload.files, and the golden does too (#351)" \
  'python3 -c "import json,sys; b=json.load(open(sys.argv[1])); g=json.load(open(sys.argv[2])); sys.exit(0 if b[\"autoload\"][\"files\"]==[\"telemetry.php\"] and \"telemetry.php\" in g[\"autoload\"][\"files\"] and g[\"autoload\"].get(\"psr-4\") else 1)" "$tmp/core_block.json" "$GOLD/composer.json"'
check "the golden bootstrap loads once and stands down without the SDK, before any provider is built" \
  'g=$GOLD/telemetry.php; a=$(grep -n "^if (defined(.OTEL_AS_CODE_BOOTSTRAPPED.)) {" $g | cut -d: -f1); b=$(grep -n "^if (!class_exists(TracerProvider::class)) {" $g | cut -d: -f1); c=$(grep -n "^\$tracerProvider = new TracerProvider(" $g | cut -d: -f1); [ -n "$a" ] && [ -n "$b" ] && [ -n "$c" ] && [ "$a" -lt "$b" ] && [ "$b" -lt "$c" ] && ! grep -q "trigger_error(" $g'
check "the summary's first step is composer update for the added packages, not a bare composer install" \
  'grep -qF "  1. composer update '"'"'open-telemetry/*'"'"'" "$GEN" && ! grep -qx "  1. composer install" "$GEN"'
check "/otel-uninstrument warns that autoload.files still names the deleted bootstrap" \
  'grep -qF "\`autoload.files\` still names it" commands/otel-uninstrument.md && grep -qF "composer dump-autoload" commands/otel-uninstrument.md'
check "the generator's composer block and the golden allow tbachert/spi (the extension's hook manager is registered only through it)" \
  'python3 -c "import json,sys; b=json.load(open(sys.argv[1])); g=json.load(open(sys.argv[2])); sys.exit(0 if b[\"config\"][\"allow-plugins\"]=={\"tbachert/spi\": True} and g[\"config\"][\"allow-plugins\"].get(\"tbachert/spi\") is True else 1)" "$tmp/core_block.json" "$GOLD/composer.json"'
check "the e2e merges the golden's allow-plugins into the app, as generated" \
  'grep -qF "update(gold[\"config\"][\"allow-plugins\"])" tests/e2e/log-trace-ids.sh'
# The logger provider lives in the bootstrap (until 0.25.24 it was a printed add-on block, which
# failed four ways when first run); the Monolog bridge is a printed line, never for Laravel.
check "the golden registers its own logger provider: builder, initializer, flushed at shutdown" \
  'g=$GOLD/telemetry.php; grep -qF "\$loggerProvider = LoggerProvider::builder()" $g && ! grep -qF "new LoggerProvider(" $g && grep -qF "        ->withLoggerProvider(\$loggerProvider)" $g && grep -qxF "    \$loggerProvider->shutdown();" $g'
check "the Monolog bridge section has no php block left to paste into telemetry.php" \
  'awk "/^### Logs \\(Monolog bridge/{h=1;next} h&&/^### /{exit} h" "$GEN" > "$tmp/bridge.md"; [ "$(grep -cx "\`\`\`php" "$tmp/bridge.md")" = 1 ] && [ "$(awk "/^\`\`\`php\$/{g=1;next} g&&/^\`\`\`\$/{exit} g" "$tmp/bridge.md" | wc -l | tr -d " ")" = 1 ]'
check "the printed pushHandler line names Globals::loggerProvider(), never the bootstrap's local variable" \
  'grep -qxF "\$logger->pushHandler(new \OpenTelemetry\Contrib\Logs\Monolog\Handler(\OpenTelemetry\API\Globals::loggerProvider(), \Monolog\Logger::DEBUG));" "$GEN" && ! grep -qF "Handler(\$loggerProvider" "$GEN"'
check "Laravel gets no Monolog bridge (its package exports the lines; both would send each twice)" \
  'grep -qF "Never print the" "$GEN" && grep -qF "Monolog handler line or add \`opentelemetry-logger-monolog\` for Laravel" "$GEN" && grep -qF "the framework is not \`laravel\`, also add" "$GEN"'
check "the e2e runs the bridge line against the golden, and Laravel's exported log line once" \
  '! grep -qF "php_monolog_addon.py" tests/e2e/log-trace-ids.sh && grep -qF "otlp_logs.py" tests/e2e/log-trace-ids.sh && grep -qF "the package exports the request'"'"'s log line once" tests/e2e/log-trace-ids.sh'
check "golden composer.json (Laravel) also carries the laravel auto-instrumentation package" \
  'grep -qF "open-telemetry/opentelemetry-auto-laravel" "$GOLD/composer.json"'

# --- guard + fixture ---
check "write-guard protects telemetry.php (otel-paths)" \
  '( source hooks/otel-paths.sh && otel_is_generated_path /x/telemetry.php )'
check "php fixture is a Laravel app (composer.json requires laravel/framework), stays greenfield" \
  'grep -qF "\"laravel/framework\"" "$FIX/composer.json" && test -f "$FIX/artisan" && test -f "$FIX/routes/web.php" \
   && ! grep -rqiE "opentelemetry|open-telemetry" "$FIX"'

# --- freshness: the manifest is an identity input, so the service never reads as always stale ---
check "the /otel-init identity regex covers composer.json" \
  'grep -q "composer\\\\.json" "$INIT"'

echo ""
echo "Results: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
