#!/usr/bin/env bash
# tests/hooks/session-summary.test.sh
# The SessionEnd summary must emit a bullet for EVERY otel file it counts — the set of
# files that trip the summary (is_otel_path) must match the set the output loop renders.
set -euo pipefail

HOOK="$(cd "$(dirname "$0")/../.." && pwd)/hooks/session-summary.sh"
PASS=0
FAIL=0

# Run the hook inside a throwaway git repo containing the given changed (untracked) files.
run_with() {
  local tmp; tmp=$(mktemp -d)
  ( cd "$tmp" && git init -q && git config user.email t@t.t && git config user.name t )
  local f
  for f in "$@"; do mkdir -p "$tmp/$(dirname "$f")"; echo "x" > "$tmp/$f"; done
  ( cd "$tmp" && bash "$HOOK" )
  rm -rf "$tmp"
}

assert_bullet() {  # name, file-that-must-appear-in-a-bullet, changed-files...
  local name="$1"; local needle="$2"; shift 2
  local out; out=$(run_with "$@")
  # A bullet for the file must exist (line starting with "- " and mentioning the file).
  if echo "$out" | grep -q "^- .*$needle"; then
    echo "PASS: $name"; PASS=$((PASS+1))
  else
    echo "FAIL: $name — counted but no bullet for '$needle'"
    echo "Output: $out"; FAIL=$((FAIL+1))
  fi
}

# Test 1: a generated bootstrap file → bullet (baseline behavior)
assert_bullet "tracing.js gets a bullet" "tracing.js" "src/tracing.js"

# Test 2: telemetry.js is counted by is_otel_path but had no output case → must get a bullet
assert_bullet "telemetry.js gets a bullet" "telemetry.js" "telemetry.js"

# Test 3: opentelemetry.js likewise must get a bullet
assert_bullet "opentelemetry.js gets a bullet" "opentelemetry.js" "app/opentelemetry.js"

# Test 4: no otel files changed → no summary at all
OUT=$(run_with "README.md" "src/index.js")
if [ -z "$OUT" ]; then
  echo "PASS: no summary when nothing otel changed"; PASS=$((PASS+1))
else
  echo "FAIL: produced output with no otel changes"; echo "Output: $OUT"; FAIL=$((FAIL+1))
fi

# --- #251: Terraform modules in any directory, and paths git quotes ---
# run_setup <shell snippet>: run the hook in a throwaway git repo after the snippet sets it up.
run_setup() {
  local tmp; tmp=$(mktemp -d)
  ( cd "$tmp" && git init -q && git config user.email t@t.t && git config user.name t && eval "$1" )
  ( cd "$tmp" && bash "$HOOK" )
  rm -rf "$tmp"
}
expect() {  # name, "has"|"lacks", fixed string, hook output
  local name="$1" mode="$2" needle="$3" out="$4" ok=1
  if echo "$out" | grep -q -F -- "$needle"; then [ "$mode" = has ] || ok=0; else [ "$mode" = lacks ] || ok=0; fi
  if [ "$ok" -eq 1 ]; then echo "PASS: $name"; PASS=$((PASS+1))
  else echo "FAIL: $name: expected output that $mode '$needle'"; echo "Output: $out"; FAIL=$((FAIL+1)); fi
}
MARK='# Generated by otel-as-code v0.0.0 on 2026-01-01.'

OUT=$(run_setup "mkdir -p infra/tf && echo '$MARK' > infra/tf/main.tf")
expect "a marked main.tf outside */observability/* (--output-dir) is reported (#251)" has '`infra/tf/main.tf`' "$OUT"

OUT=$(run_setup "mkdir -p infra/tf && echo '$MARK' > infra/tf/variables.tf && echo '$MARK' > infra/tf/outputs.tf")
expect "a marked variables.tf is reported" has '`infra/tf/variables.tf`' "$OUT"
expect "a marked outputs.tf is reported" has '`infra/tf/outputs.tf`' "$OUT"

OUT=$(run_setup "mkdir -p infra/tf && echo 'resource \"null_resource\" \"x\" {}' > infra/tf/main.tf")
expect "a hand-written main.tf (no marker) is not reported" lacks 'main.tf' "$OUT"

OUT=$(run_setup "mkdir -p infra/observability/datadog && echo 'resource \"null_resource\" \"x\" {}' > infra/observability/datadog/main.tf")
expect "a hand-written main.tf under */observability/* is not reported either" lacks 'main.tf' "$OUT"

OUT=$(run_setup "mkdir -p infra/observability/datadog && echo '$MARK' > infra/observability/datadog/main.tf")
expect "a marked vendor module keeps its vendor bullet" has 'Datadog observability module (`infra/observability/datadog/main.tf`)' "$OUT"

OUT=$(run_setup "mkdir -p 'my dir' && echo x > 'my dir/tracing.js'")
expect "a path with a space, which git quotes, is reported whole (#251)" has '`my dir/tracing.js`' "$OUT"

OUT=$(run_setup "mkdir -p 'café' && echo x > 'café/tracing.py'")
expect "a non-ASCII path, which git quotes and escapes, is reported as written" has '`café/tracing.py`' "$OUT"

OUT=$(run_setup "echo x > tracing.js && git add tracing.js && git commit -qm init && mkdir -p 'new dir' && git mv tracing.js 'new dir/tracing.js'")
expect "a staged rename reports the new path" has '`new dir/tracing.js`' "$OUT"
expect "a staged rename does not report the old path as its own file" lacks '(`tracing.js`)' "$OUT"

echo ""
echo "Results: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
