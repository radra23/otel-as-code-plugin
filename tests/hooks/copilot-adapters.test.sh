#!/usr/bin/env bash
# tests/hooks/copilot-adapters.test.sh
# Verify the GitHub Copilot CLI hook adapters translate Copilot's payloads (the ones captured in
# tests/hooks/fixtures/copilot/) to the plugin's guardrails, reusing write-guard.sh /
# semconv-lint.sh, and answer in the JSON Copilot acts on.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PRE="$ROOT/hooks/copilot/pre-tool-use.py"
POST="$ROOT/hooks/copilot/post-tool-use.py"
FIX="$ROOT/tests/hooks/fixtures/copilot"
PASS=0
FAIL=0

# A captured fixture with its scrubbed repo path (/work/fixture) pointed at a real directory.
fixture() {  # name, dir
  sed "s#/work/fixture#$2#g" "$FIX/$1"
}

# A camelCase Copilot payload; toolArgs is a JSON string, as Copilot sends it.
payload() {  # cwd, toolName, toolArgs-json
  python3 -c 'import json,sys; print(json.dumps({"sessionId":"0","timestamp":0,"cwd":sys.argv[1],"toolName":sys.argv[2],"toolArgs":sys.argv[3]}))' "$1" "$2" "$3"
}

check() {  # name, expect(deny|allow|context|substr), output, [needle]
  local name="$1" expect="$2" out="$3" needle="${4:-}"
  case "$expect" in
    deny)    echo "$out" | python3 -c 'import json,sys; sys.exit(json.load(sys.stdin).get("permissionDecision") != "deny")' 2>/dev/null && r=1 || r=0 ;;
    allow)   [ -z "$out" ] && r=1 || r=0 ;;
    context) echo "$out" | python3 -c 'import json,sys; sys.exit(not json.load(sys.stdin).get("additionalContext"))' 2>/dev/null && r=1 || r=0 ;;
    substr)  echo "$out" | grep -qF -- "$needle" && r=1 || r=0 ;;
  esac
  if [ "$r" -eq 1 ]; then echo "PASS: $name"; PASS=$((PASS+1)); else echo "FAIL: $name"; echo "  out: $out"; FAIL=$((FAIL+1)); fi
}

GENERATED=$'# Generated by otel-as-code v0.1.0\n# Re-run /otel-instrument to regenerate.\n'

# 1. The captured `edit` of a marker-stamped tracing.py is denied, in Copilot's top-level shape.
TMP=$(mktemp -d); printf '%s' "$GENERATED" > "$TMP/tracing.py"
OUT=$(fixture preToolUse.camel.edit.stdin.json "$TMP" | python3 "$PRE")
check "pre: denies the captured edit of a generated tracing.py" deny "$OUT"
check "pre: the reason is write-guard's own" substr "$OUT" "blocking overwrite of existing generated OTel file"
# Teeth: the same payload sent straight to write-guard.sh, as hooks/hooks.json would, is let
# through. That is the gap the bridge exists for (docs/agents/copilot-spike.md).
set +e; fixture preToolUse.camel.edit.stdin.json "$TMP" | bash "$ROOT/hooks/write-guard.sh" 2>/dev/null; RC=$?; set -e
check "teeth: write-guard.sh alone does not block the raw Copilot payload" substr "rc=$RC" "rc=0"

# 2. The same edit with path-scoped --force is allowed.
mkdir -p "$TMP/.claude"; echo "$TMP/tracing.py" > "$TMP/.claude/.otel-force"
OUT=$(fixture preToolUse.camel.edit.stdin.json "$TMP" | python3 "$PRE")
check "pre: --force sentinel lets the edit through" allow "$OUT"
rm -rf "$TMP"

# 3. A tracing.py without the ownership marker is the user's own and is not blocked.
TMP=$(mktemp -d); printf '# Re-run /otel-instrument to regenerate.\n' > "$TMP/tracing.py"
OUT=$(fixture preToolUse.camel.edit.stdin.json "$TMP" | python3 "$PRE")
check "pre: allows editing a markerless tracing.py" allow "$OUT"
rm -rf "$TMP"

# 4. A new file and a tool that writes nothing are allowed, silently.
TMP=$(mktemp -d)
OUT=$(fixture postToolUse.camel.create.stdin.json "$TMP" | python3 "$PRE")
check "pre: allows creating a new file" allow "$OUT"
OUT=$(payload "$TMP" report_intent '{"intent":"Editing files"}' | python3 "$PRE")
check "pre: ignores a tool that is not create/edit" allow "$OUT"
OUT=$(echo 'not json' | python3 "$PRE")
check "pre: ignores a payload that is not JSON" allow "$OUT"

# 5. Business attributes in the context cache must be confirmed, for create and for edit.
mkdir -p "$TMP/.claude"
ARGS=$(python3 -c 'import json,sys; print(json.dumps({"path":sys.argv[1]+"/.claude/otel-context.json","file_text":json.dumps({"schemaVersion":"1","businessAttrs":[{"name":"biz.checkout.rate","confirmed":False}]})}))' "$TMP")
OUT=$(payload "$TMP" create "$ARGS" | python3 "$PRE")
check "pre: denies creating the cache with an unconfirmed business attribute" deny "$OUT"
check "pre: names the unconfirmed attribute" substr "$OUT" "biz.checkout.rate"
echo '{"schemaVersion":"1","businessAttrs":[{"name":"biz.checkout.rate","confirmed":true}]}' > "$TMP/.claude/otel-context.json"
ARGS=$(python3 -c 'import json,sys; print(json.dumps({"path":sys.argv[1]+"/.claude/otel-context.json","old_str":"\"confirmed\":true","new_str":"\"confirmed\":false"}))' "$TMP")
OUT=$(payload "$TMP" edit "$ARGS" | python3 "$PRE")
check "pre: denies an edit that unconfirms a business attribute" deny "$OUT"
ln -s .claude/otel-context.json "$TMP/ctx-alias.json"
ARGS=$(python3 -c 'import json,sys; print(json.dumps({"path":sys.argv[1]+"/ctx-alias.json","file_text":"{}"}))' "$TMP")
OUT=$(payload "$TMP" create "$ARGS" | python3 "$PRE")
check "pre: denies a write that reaches the cache through a symlink" deny "$OUT"
rm -rf "$TMP"

# 6. postToolUse: the captured create (http.method) reaches the model as additionalContext.
TMP=$(mktemp -d)
fixture postToolUse.camel.create.stdin.json "$TMP" | python3 -c 'import json,sys; a=json.loads(json.load(sys.stdin)["toolArgs"]); open(a["path"],"w").write(a["file_text"])'
OUT=$(fixture postToolUse.camel.create.stdin.json "$TMP" | python3 "$POST")
check "post: lint findings come back as additionalContext" context "$OUT"
check "post: flags the deprecated http.method" substr "$OUT" "http.method"
OUT=$(fixture postToolUse.camel.create.stdin.json "$TMP" | OTEL_STRICT=1 python3 "$POST")
check "post: strict mode frames severe findings as must-fix" substr "$OUT" "STRICT: severe violation(s) must be fixed"
printf 'from opentelemetry import trace\nspan = trace.get_current_span()\nspan.set_attribute("http.request.method", "GET")\n' > "$TMP/attrs.py"
OUT=$(fixture postToolUse.camel.create.stdin.json "$TMP" | python3 "$POST")
check "post: a clean file gets no output" allow "$OUT"
rm -rf "$TMP"

# 7. postToolUse re-reads the cache from disk after a write to it.
TMP=$(mktemp -d); mkdir -p "$TMP/.claude"
echo '{"schemaVersion":"1","businessAttrs":[{"name":"biz.cart.size","confirmed":false}]}' > "$TMP/.claude/otel-context.json"
ARGS=$(python3 -c 'import json,sys; print(json.dumps({"path":sys.argv[1]+"/.claude/otel-context.json","old_str":"x","new_str":"y"}))' "$TMP")
OUT=$(payload "$TMP" edit "$ARGS" | python3 "$POST")
check "post: an unconfirmed attribute on disk after a write is a must-fix" substr "$OUT" "MUST FIX"
rm -rf "$TMP"

# 8. The root hooks.json Copilot loads: flat format, camelCase events (which select the payload
# format above), and every command names an adapter that exists.
check "hooks.json: flat Copilot format with camelCase events, adapters exist" substr "$(python3 - "$ROOT" <<'PY'
import json, os, re, sys
root = sys.argv[1]
cfg = json.load(open(os.path.join(root, "hooks.json")))
ok = cfg.get("version") == 1 and set(cfg["hooks"]) == {"preToolUse", "postToolUse"}
for entries in cfg["hooks"].values():
    for e in entries:
        m = re.fullmatch(r'python3 "\$\{CLAUDE_PLUGIN_ROOT\}/(hooks/copilot/[a-z-]+\.py)"', e.get("bash", ""))
        ok = ok and e.get("type") == "command" and bool(m) and os.path.isfile(os.path.join(root, m.group(1)))
print("ok" if ok else "bad")
PY
)" "ok"

echo ""
echo "copilot-adapters: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
