#!/usr/bin/env bash
# tests/hooks/write-guard.test.sh
# Tests for the write-guard PreToolUse hook.
# Usage: bash tests/hooks/write-guard.test.sh
set -euo pipefail

HOOK="hooks/write-guard.sh"
PASS=0
FAIL=0

# On MSYS / Git Bash (the Windows CI job), an ABSOLUTE mktemp temp path (`/tmp/…` or a Git-Bash
# mount) does not round-trip through the NATIVE Windows python the hook runs under — native python
# resolves MSYS `/tmp` to `C:\tmp`, so a temp-path force-match cannot be exercised faithfully here.
# Real `--force` usage under a repo path IS covered on Windows by the "matches a Windows path
# against its Git Bash spelling" case and the relative-entry cases (all of which pass on Windows).
# So the handful of ABSOLUTE-temp-path force cases below are skipped on MSYS only; they run in full
# on Linux/macOS. See PR for #55.
IS_MSYS=0
case "$(uname -s 2>/dev/null)" in MINGW*|MSYS*|CYGWIN*) IS_MSYS=1 ;; esac

run_test() {
  local name="$1"; local input="$2"; local expect_exit="$3"
  actual_exit=0
  echo "$input" | bash "$HOOK" > /dev/null 2>&1 || actual_exit=$?
  if [ "$actual_exit" -eq "$expect_exit" ]; then
    echo "PASS: $name"
    PASS=$((PASS+1))
  else
    echo "FAIL: $name (expected exit $expect_exit, got $actual_exit)"
    FAIL=$((FAIL+1))
  fi
}

# Test 1: Write to a non-OTel file → allow (exit 0)
run_test "allow non-otel file" \
  '{"tool_name":"Write","tool_input":{"file_path":"src/utils.js"}}' 0

