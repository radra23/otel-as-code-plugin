# --- Issue 12: --force must survive a path-shape mismatch --------------------------------
# The tool reports file_path in the host's convention while the sentinel is written from a
# shell that may spell the same file differently. An exact string compare (grep -Fxq) can
# never match across those shapes, so --force silently did nothing on Windows.
#
# force_shape <label> <sentinel line, %s = the real path> — asserts the overwrite is allowed.
force_shape() {
  local label="$1" line="$2"
  if [ "$IS_MSYS" = 1 ] && case "$2" in *%s*) true ;; *) false ;; esac; then
    echo "SKIP (MSYS, absolute temp path): --force honours $label"; return
  fi
  local tmp; tmp=$(mktemp -d)
  mkdir -p "$tmp/api/src" "$tmp/.claude"
  printf '# generated by otel-as-code v0.1.0\nexisting content\n' >"$tmp/api/src/tracing.ts"
  # shellcheck disable=SC2059
  printf "$line\n" "$tmp" > "$tmp/.claude/.otel-force"
  local input="{\"tool_name\":\"Write\",\"tool_input\":{\"file_path\":\"$tmp/api/src/tracing.ts\"}}"
  local rc=0
  echo "$input" | CLAUDE_PROJECT_DIR="$tmp" bash "$HOOK" > /dev/null 2>&1 || rc=$?
  if [ "$rc" -eq 0 ]; then
    echo "PASS: --force honours $label"; PASS=$((PASS+1))
  else
    echo "FAIL: --force honours $label (expected 0, got $rc)"; FAIL=$((FAIL+1))
  fi
  rm -rf "$tmp"
}

force_shape "a project-relative entry"        "api/src/tracing.ts"
force_shape "a ./-prefixed entry"             "./api/src/tracing.ts"
force_shape "an entry with . and .. segments" "%s/api/../api/./src/tracing.ts"
force_shape "trailing whitespace"             "%s/api/src/tracing.ts   "

# The Windows case, exercised on any host: the guard sees a backslashed drive path and the
# sentinel holds the Git Bash spelling of the same file. Both are normalised to /c/... so
# they compare equal — this is the exact pair that could never match before.
WIN_TOOL='C:\Users\JC\Repos\portal\api\src\tracing.ts'
WIN_SENTINEL='/c/Users/JC/Repos/portal/api/src/tracing.ts'
if python3 - "$WIN_TOOL" "$WIN_SENTINEL" <<'PY'
import subprocess, sys, tempfile, os
tool, sentinel = sys.argv[1], sys.argv[2]
d = tempfile.mkdtemp()
f = os.path.join(d, "force")
open(f, "w").write(sentinel + "\n")
sys.exit(subprocess.run(
    ["python3", "hooks/otel-force-match.py", tool, "/c/Users/JC/Repos/portal", f]
).returncode)
PY
then
  echo "PASS: --force matches a Windows path against its Git Bash spelling"
  PASS=$((PASS+1))
else
  echo "FAIL: --force matches a Windows path against its Git Bash spelling"
  FAIL=$((FAIL+1))
fi

# Teeth check: normalisation must not turn --force into a blanket disable. A sentinel
# naming a *different* file in the same directory still blocks.
force_shape_blocks() {
  local label="$1" line="$2"
  local tmp; tmp=$(mktemp -d)
  mkdir -p "$tmp/api/src" "$tmp/.claude"
  printf '# generated by otel-as-code v0.1.0\nexisting content\n' >"$tmp/api/src/tracing.ts"
  # shellcheck disable=SC2059
  printf "$line\n" "$tmp" > "$tmp/.claude/.otel-force"
  local input="{\"tool_name\":\"Write\",\"tool_input\":{\"file_path\":\"$tmp/api/src/tracing.ts\"}}"
  local rc=0
  echo "$input" | CLAUDE_PROJECT_DIR="$tmp" bash "$HOOK" > /dev/null 2>&1 || rc=$?
  if [ "$rc" -eq 2 ]; then
    echo "PASS: --force still blocks $label"; PASS=$((PASS+1))
  else
    echo "FAIL: --force still blocks $label (expected 2, got $rc)"; FAIL=$((FAIL+1))
  fi
  rm -rf "$tmp"
}

force_shape_blocks "a sibling file in the same dir" "%s/api/src/telemetry.ts"
force_shape_blocks "the same basename elsewhere"    "%s/web/src/tracing.ts"
force_shape_blocks "an empty sentinel"              ""

# --- Issue 7: the guard blocks only files WE generated, not any file that shares the name ----
