# --- Issue 13: the protected set is derived, not hand-listed -----------------------------
# telemetry.ts is generated by this plugin for every TypeScript project and used to be
# absent from the guard's hand-maintained basename list (only telemetry.js / telemetry.py
# were there), leaving the more valuable of the two generated files unprotected.
expect_blocked() {
  local name="$1"
  local tmp; tmp=$(mktemp -d)
  printf '# generated by otel-as-code v0.1.0\nexisting content\n' >"$tmp/$name"
  local input="{\"tool_name\":\"Write\",\"tool_input\":{\"file_path\":\"$tmp/$name\"}}"
  local rc=0
  echo "$input" | bash "$HOOK" > /dev/null 2>&1 || rc=$?
  if [ "$rc" -eq 2 ]; then
    echo "PASS: protects existing $name"; PASS=$((PASS+1))
  else
    echo "FAIL: protects existing $name (expected 2, got $rc)"; FAIL=$((FAIL+1))
  fi
  rm -rf "$tmp"
}

for name in telemetry.ts telemetry.go tracing.mjs opentelemetry.py tracing.rb; do
  expect_blocked "$name"
done

