# Test 10b (#33): an interpreter that RESOLVES but does not RUN (the Windows Store `python3`
# alias stub: on PATH, `command -v` succeeds, but executing it errors) must FAIL CLOSED, not
# silently allow the write. Simulate the stub with an executable that exits non-zero, pointed to
# via OTEL_HOOK_PYTHON. Target a brand-new file that would otherwise be ALLOWED, so a pass here
# can only mean the guard blocked because it could not verify — not because the file was protected.
STUBDIR=$(mktemp -d)
printf '#!/bin/sh\necho "Python was not found; run without arguments to install from the Microsoft Store" >&2\nexit 9\n' > "$STUBDIR/python3-stub"
chmod +x "$STUBDIR/python3-stub"
INPUT='{"tool_name":"Write","tool_input":{"file_path":"src/brand-new.js"}}'
actual_exit=0
echo "$INPUT" | OTEL_HOOK_PYTHON="$STUBDIR/python3-stub" bash "$HOOK" > /dev/null 2>&1 || actual_exit=$?
