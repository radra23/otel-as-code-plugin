# Test (#53): the --force match must use the RESOLVED working interpreter, not a hardcoded
# `python3`. Prepend a failing `python3` stub to PATH and point OTEL_HOOK_PYTHON at a real
# interpreter; a marked file listed in the sentinel must still be ALLOWED (exit 0). Before the
# fix, force-match shelled out to the stub `python3`, failed, and --force silently no-op'd → block.
REALPY=$(command -v python3 || true)
if [ -n "$REALPY" ]; then
  STUBDIR=$(mktemp -d)
  printf '#!/bin/sh\nexit 9\n' > "$STUBDIR/python3"; chmod +x "$STUBDIR/python3"
  TMP=$(mktemp -d)
  printf '# generated by otel-as-code v0.1.0\nx\n' > "$TMP/tracing.js"
  mkdir -p "$TMP/.claude"; echo "$TMP/tracing.js" > "$TMP/.claude/.otel-force"
  INPUT="{\"tool_name\":\"Write\",\"tool_input\":{\"file_path\":\"$TMP/tracing.js\"}}"
  actual_exit=0
  echo "$INPUT" | PATH="$STUBDIR:$PATH" OTEL_HOOK_PYTHON="$REALPY" CLAUDE_PROJECT_DIR="$TMP" bash "$HOOK" > /dev/null 2>&1 || actual_exit=$?
  if [ "$actual_exit" -eq 0 ]; then
    echo "PASS: --force match uses the resolved interpreter, not a hardcoded python3"
    PASS=$((PASS+1))
  elif [ "$IS_MSYS" = 1 ]; then
    echo "SKIP (MSYS, absolute temp path): force-match uses the resolved interpreter (#53)"
  else
    echo "FAIL: force-match still hardcodes python3 (#53) (expected 0, got $actual_exit)"
    FAIL=$((FAIL+1))
  fi
  rm -rf "$STUBDIR" "$TMP"
fi

echo ""
