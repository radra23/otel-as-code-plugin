#!/usr/bin/env bash
# tests/hooks/dotnet-generator.test.sh
# Locks three .NET generator fixes that all came from generated output that only worked because the
# model overrode its own instructions:
#   #182  OpenTelemetry.cs is written into the project that owns runnableEntry, not rootDir
#   #183  the OTLP exporter is attached only when an endpoint is configured, and the environment
#         label falls back through ASPNETCORE_ENVIRONMENT before "development"
#   #186  the /otel-instrument refusal is language-neutral and points to what does apply
# tests/e2e/dotnet-placement.sh is the build-level proof for #182.
set -uo pipefail
cd "$(dirname "$0")/../.."
pass=0; fail=0
check() { if eval "$2"; then echo "PASS: $1"; pass=$((pass+1)); else echo "FAIL: $1"; fail=$((fail+1)); fi; }

GEN="agents/instrumentation-gen.md"
CMD="commands/otel-instrument.md"
GOLD="tests/snapshots/instrument/dotnet/OpenTelemetry.cs"
NET=$(sed -n '/^## .NET (code-based SDK)/,/^## Go (manual SDK wiring)/p' "$GEN")   # captured once: grep -q + pipefail would race
STEP2=$(sed -n '/^3\. Validate the chosen service before generating/,/^4\. Derive/p' "$CMD")
net() { grep -qF -- "$1" <<<"$NET"; }
step2() { grep -qF -- "$1" <<<"$STEP2"; }

# ---- #182 placement ----
check "generator places the file in the project that owns runnableEntry, not the service root" \
  'net "### \`OpenTelemetry.cs\` (in the project that owns \`runnableEntry\`)" && ! net "### \`OpenTelemetry.cs\` (service root)"'
check "generator states the rule: walk up from runnableEntry to the first *.csproj" \
  'net "walk up to the" && net "first directory that contains a \`*.csproj\`" && net "\`rootDir\`" && net "decides identity, not compile membership"'
check "generator prints dotnet add against the resolved csproj and the resolved path" \
  'net "dotnet add <path/to/Project.csproj> package OpenTelemetry.Extensions.Hosting" && net "<resolved path, e.g. src/Svc/OpenTelemetry.cs>"'
check "nested fixture: solution at the root, project one level down" \
  'test -f fixtures/dotnet-nested/svc.sln && test -f fixtures/dotnet-nested/src/Svc/Svc.csproj && test -f fixtures/dotnet-nested/src/Svc/Program.cs && ! ls fixtures/dotnet-nested/*.csproj >/dev/null 2>&1'
check "nested fixture stays greenfield (no OTel package, no generated file)" \
  '! grep -rqiE "OpenTelemetry\.(Extensions|Instrumentation|Exporter)|generated by otel-as-code" fixtures/dotnet-nested --include=*.csproj --include=*.cs'
check "the build-level placement proof exists and is wired into CI" \
  'test -f tests/e2e/dotnet-placement.sh && grep -qF "dotnet-placement.sh" .github/workflows/ci.yml'

# ---- #183 exporter + environment ----
check "golden gates the exporter on an endpoint and honours OTEL_*_EXPORTER=none" \
  'grep -qF "bool Exporting(string signalEndpoint, string exporterKey)" "$GOLD" && grep -qF "OTEL_EXPORTER_OTLP_ENDPOINT" "$GOLD" && grep -qF "\"none\"" "$GOLD"'
check "golden never attaches the exporter unconditionally" \
  '! grep -qE "^ +\.AddOtlpExporter\(\)" "$GOLD" && [ "$(grep -c "AddOtlpExporter()" "$GOLD")" -eq 2 ] && [ "$(grep -B1 "AddOtlpExporter()" "$GOLD" | grep -c "if (Exporting(")" -eq 2 ]'
check "golden environment chain: DEPLOYMENT_ENV, ASPNETCORE_ENVIRONMENT, DOTNET_ENVIRONMENT, then default" \
  'grep -qF "Set(\"DEPLOYMENT_ENV\")" "$GOLD" && grep -qF "ASPNETCORE_ENVIRONMENT" "$GOLD" && grep -qF "DOTNET_ENVIRONMENT" "$GOLD" && grep -qF "?? \"development\"" "$GOLD"'
check "golden keeps the structure pins.test.sh relies on" \
  'grep -qF "IServiceCollection AddOtelObservability" "$GOLD" && grep -qF ".WithTracing(" "$GOLD" && grep -qF ".WithMetrics(" "$GOLD"'
check "generator documents the gate and the environment chain, and that the golden is the shape to match" \
  'net "Gate the exporter, as every other language does (#183)" && net "ASPNETCORE_ENVIRONMENT" && net "Match the golden'"'"'s shape"'
check "generator no longer says the exporter defaults to localhost with nothing configured" \
  '! net "with none set it defaults to \`http://localhost:4317\`" && ! net "the OTLP exporter defaults to http://localhost:4317 with nothing configured"'
check "the logs add-on is gated on the endpoint too" \
  'net "if (!string.IsNullOrWhiteSpace(builder.Configuration[\"OTEL_EXPORTER_OTLP_ENDPOINT\"]))"'
check "Step 8 groups .NET with the languages that export nowhere until configured" \
  'grep -qF "Node.js/Python/Go/Rust/.NET code defaults every exporter to \`none\`" "$CMD" && ! grep -qF "The .NET OTLP exporter and the" "$CMD"'

# ---- #186 refusal ----
check "refusal sentence is language-neutral and no longer names a Node SDK bootstrap" \
  'step2 "server-side SDK bootstrap for a browser bundle" && ! grep -qF "Generating a Node SDK bootstrap" "$CMD"'
check "refusal points a workload with no source to /otel-remediate" \
  'step2 "/otel-remediate --service <id> proposes the deployment-config change instead"'
check "refusal points every other in-scope refusal to /otel-evaluate, and gives a browser bundle no pointer" \
  'step2 "/otel-evaluate --service <id> audits what is already there" && step2 "a browser bundle,"'

echo ""
echo "Results: $pass passed, $fail failed"
[ "$fail" -eq 0 ]
