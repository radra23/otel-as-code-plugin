#!/usr/bin/env python3
"""Write /otel-test's telemetry test: one file per service that sends one request through the
service and fails unless the expected spans and metrics came out.

The file is rendered from a small spec, never written freehand, so every generated test has the
same shape and every value that reaches the code is checked first.

  telemetry_test.py render --spec FILE|- [--root R] [--dry-run] [--force]
      Render the test for the spec (JSON; `-` reads stdin) into the service directory:
        nodejs  otel.test.cjs   node:test. Starts the service as production does, on a free port,
                                with OTLP pointed at a receiver inside the test.
        python  test_otel.py    unittest (pytest runs it too). Calls the ASGI or WSGI app in
                                process, with the SDK's in-memory span exporter and metric reader.
      Prints the diff, then writes (--dry-run: writes nothing, exits 1 if there is a diff). A file
      of that name that otel-as-code did not generate is never overwritten; one it did generate
      needs --force.

  telemetry_test.py path --spec FILE|- [--root R]
      Print where the test for the spec goes, relative to the root.

The spec:
  {"language": "nodejs" | "python",
   "serviceRoot": "api",                 directory of the service, relative to the root
   "serviceName": "checkout-api",
   "start": ["-r", "./tracing.js", "index.js"],     nodejs: the arguments node starts the service with
   "startScript": "start",                          nodejs, optional: the package.json script that IS
                                                    that command; the test then reads it on every run
   "portEnv": "PORT",                               nodejs: the variable the service reads its port from
   "app": "main:app", "interface": "asgi" | "wsgi", python: the app object the server runs
   "bootstrap": "tracing",                          python, optional: the bootstrap's module name; the
                                                    test then fails if importing the app does not import it
   "env": {"AUTH_SECRET": "test-only-secret"},      optional: fixed values the service needs before it answers
                                                    (dummy secrets, a base URL). Names and values are plain
                                                    text in the test file: never a real secret. OTEL_* names
                                                    and the port variable are the test's own and are refused.
   "request": {"method": "POST", "path": "/checkout", "json": {...}, "expectStatus": 200},
   "serverSpan": "POST /checkout",       the request's own span, as the instrumentation names it
   "spans": ["orders.checkout"],         spans /otel-enrich added on this code path
   "metrics": ["com.myorg.checkout.order_placed"],
   "notCovered": [{"name": "...", "reason": "..."}]}    what this request cannot reach, and why

Exit 0 written (or nothing to do); 1 --dry-run found changes; 2 REFUSED, with one line saying why
and nothing written. Standard library only.
"""
import argparse
import difflib
import json
import os
import re
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
MARKER = "generated by otel-as-code"
FILE_NAMES = {"nodejs": "otel.test.cjs", "python": "test_otel.py"}
METHODS = ("GET", "POST", "PUT", "PATCH", "DELETE")
ARG_RE = re.compile(r"^[A-Za-z0-9_./@=:+-]{1,200}$")
ENV_RE = re.compile(r"^[A-Z_][A-Z0-9_]{0,63}$")
ENV_VALUE_RE = re.compile(r"^[\x20-\x7e]{0,200}$")
APP_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_.]{0,199}:[A-Za-z_][A-Za-z0-9_]{0,99}$")
PATH_RE = re.compile(r"^/[A-Za-z0-9_\-./~%?=&:,+@]{0,500}$")
SERVER_SPAN_RE = re.compile(r"^[A-Za-z0-9_ ./:{}<>*\[\]\-]{1,200}$")
SPAN_NAME_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.\-/ ]{0,99}$")
METRIC_NAME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_.\-/]{0,254}$")
SERVICE_NAME_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.\-/ ]{0,99}$")


class Refused(Exception):
    pass


def plugin_version():
    try:
        with open(os.path.join(HERE, "..", ".claude-plugin", "plugin.json"), encoding="utf-8") as f:
            return json.load(f)["version"]
    except (OSError, ValueError, KeyError):
        return "unknown"


def need(cond, msg):
    if not cond:
        raise Refused(msg)


def names(spec, key, pattern, what):
    value = spec.get(key, [])
    need(isinstance(value, list) and all(isinstance(v, str) for v in value), f"`{key}` must be a list of names.")
    for v in value:
        need(pattern.fullmatch(v), f"`{key}`: {v!r} is not a plain {what} name.")
    need(len(set(value)) == len(value), f"`{key}` lists a name twice.")
    return value


def check_spec(spec):
    need(isinstance(spec, dict), "the spec must be a JSON object.")
    lang = spec.get("language")
    need(lang in FILE_NAMES, "`language` must be nodejs or python (the languages /otel-test supports).")
    for key in ("serviceRoot", "serviceName", "serverSpan"):
        need(isinstance(spec.get(key), str) and spec[key], f"`{key}` is required.")
    need(SERVICE_NAME_RE.fullmatch(spec["serviceName"]), "`serviceName` must be a plain name.")
    need(SERVER_SPAN_RE.fullmatch(spec["serverSpan"]),
         "`serverSpan` must be the request span's name, such as `POST /checkout`, `GET /items/{id}` or `GET /items/[id]`.")
    req = spec.get("request")
    need(isinstance(req, dict), "`request` is required: {method, path, expectStatus}.")
    need(req.get("method") in METHODS, f"`request.method` must be one of {', '.join(METHODS)}.")
    need(isinstance(req.get("path"), str) and PATH_RE.fullmatch(req["path"]),
         "`request.path` must be a URL path starting with / (letters, digits and URL punctuation).")
    status = req.get("expectStatus", 200)
    need(isinstance(status, int) and not isinstance(status, bool) and 100 <= status <= 599,
         "`request.expectStatus` must be an HTTP status code.")
    need("json" not in req or req["method"] != "GET", "a GET request carries no `json` body.")
    env = spec.get("env", {})
    need(isinstance(env, dict) and len(env) <= 30 and all(
        isinstance(k, str) and ENV_RE.fullmatch(k) and isinstance(v, str) and ENV_VALUE_RE.fullmatch(v)
        for k, v in env.items()),
        "`env` must map environment variable names to plain text values (printable ASCII, no newline).")
    need(not any(k.startswith("OTEL_") or k == spec.get("portEnv", "PORT") for k in env),
         "`env` may not set an OTEL_* variable or the port variable: the test sets those itself.")
    spans = names(spec, "spans", SPAN_NAME_RE, "span")
    metrics = names(spec, "metrics", METRIC_NAME_RE, "metric")
    need(spec["serverSpan"] not in spans, "`spans` repeats the server span.")
    not_covered = spec.get("notCovered", [])
    need(isinstance(not_covered, list) and all(
        isinstance(n, dict) and isinstance(n.get("name"), str) and isinstance(n.get("reason"), str)
        for n in not_covered), "`notCovered` must be a list of {name, reason}.")
    if lang == "nodejs":
        start = spec.get("start")
        need(isinstance(start, list) and start and all(isinstance(a, str) and ARG_RE.fullmatch(a) for a in start),
             "`start` must be the list of arguments node runs the service with, e.g. [\"-r\", \"./tracing.js\", \"index.js\"].")
        need(ENV_RE.fullmatch(spec.get("portEnv", "PORT")), "`portEnv` must be an environment variable name.")
        need("startScript" not in spec or (isinstance(spec["startScript"], str)
                                           and re.fullmatch(r"[A-Za-z0-9_:.-]{1,60}", spec["startScript"])),
             "`startScript` must be the name of a package.json script, such as start.")
    else:
        need(isinstance(spec.get("app"), str) and APP_RE.fullmatch(spec["app"]),
             "`app` must be `module:attribute`, the app object the server runs (e.g. main:app).")
        need(spec.get("interface") in ("asgi", "wsgi"), "`interface` must be asgi or wsgi.")
        need("bootstrap" not in spec or (isinstance(spec["bootstrap"], str)
                                         and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_.]{0,199}", spec["bootstrap"])),
             "`bootstrap` must be the module name of the generated bootstrap, such as tracing.")
    return lang, spans, metrics, not_covered


def comment_text(s):
    """One line of comment: no newline, no comment terminator, printable ASCII only."""
    return re.sub(r"[^\x20-\x7e]", " ", s).replace("*/", "* /").strip()[:300]


def fill(template, fills):
    """Fill every placeholder in ONE pass. Filling them one after another would search the text
    already inserted, so a request body containing `__SPANS__` would have code-shaped JSON
    substituted into the middle of its string literal."""
    return re.sub(r"__[A-Z_]+__", lambda m: fills[m.group(0)], template)


def not_covered_lines(not_covered, lead):
    if not not_covered:
        return []
    out = [f"{lead}", f"{lead} Not covered by this test (this request does not reach them):"]
    for n in not_covered:
        out.append(f"{lead}   - {comment_text(n['name'])}: {comment_text(n['reason'])}")
    return out


def env_lines(spec, lead):
    env = spec.get("env", {})
    if not env:
        return []
    return [f"{lead}", f"{lead} Fixed environment for the service (test-only values, never real secrets): "
            + ", ".join(sorted(env))]


