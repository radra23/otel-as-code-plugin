def load_spec(arg):
    try:
        text = sys.stdin.read() if arg == "-" else open(arg, encoding="utf-8").read()
        return json.loads(text)
    except OSError as e:
        raise Refused(f"can't read the spec: {e}")
    except ValueError as e:
        raise Refused(f"the spec is not valid JSON ({e}).")


def target(root, spec, lang):
    base = os.path.realpath(root)
    sdir = os.path.realpath(os.path.join(base, spec["serviceRoot"]))
    need((sdir == base or sdir.startswith(base + os.sep)) and os.path.isdir(sdir),
         f"`serviceRoot` {spec['serviceRoot']!r} is not a directory under {base}.")
    full = os.path.join(sdir, FILE_NAMES[lang])
    need(not os.path.islink(full), f"{os.path.relpath(full, base)} is a symbolic link; not written.")
    return base, sdir, full


def write_atomically(path, text):
    fd, tmp = tempfile.mkstemp(prefix=".otel-test.", suffix=".tmp", dir=os.path.dirname(path))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def cmd_render(args):
    spec = load_spec(args.spec)
    lang, spans, metrics, not_covered = check_spec(spec)
    base, sdir, full = target(args.root, spec, lang)
    rel = os.path.relpath(full, base)
    if lang == "nodejs":
        if spec.get("startScript"):
            try:
                with open(os.path.join(sdir, "package.json"), encoding="utf-8") as f:
                    declared = (json.load(f).get("scripts") or {}).get(spec["startScript"])
            except (OSError, ValueError):
                declared = None
            need(isinstance(declared, str) and declared.split() == ["node"] + spec["start"],
                 f"package.json \"scripts.{spec['startScript']}\" is {declared!r}, not `node {' '.join(spec['start'])}`; "
                 f"make `start` match it, or drop `startScript`.")
        script = next((a for a in spec["start"] if not a.startswith("-") and a.endswith((".js", ".cjs", ".mjs"))
                       and os.path.isfile(os.path.join(sdir, a))), None)
        need(script, f"none of the `start` arguments is a script that exists under {spec['serviceRoot']}.")
    else:
        module = spec["app"].split(":")[0].replace(".", os.sep)
        need(os.path.isfile(os.path.join(sdir, module + ".py")) or os.path.isdir(os.path.join(sdir, module)),
             f"the module in `app` ({spec['app']}) is not under {spec['serviceRoot']}.")
    new = (render_node if lang == "nodejs" else render_python)(spec, spans, metrics, not_covered)
    old = ""
    if os.path.exists(full):
        with open(full, encoding="utf-8", newline="") as f:
            old = f.read()
        need(MARKER in old, f"{rel} exists and was not generated by otel-as-code; it is never overwritten. "
                            f"Move or rename it first.")
        if old == new:
            print(f"OK: {rel} is already up to date")
            return 0
        need(args.force or args.dry_run, f"{rel} exists (generated earlier); pass --force to regenerate it.")
    sys.stdout.writelines(difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                               f"a/{rel}" if old else "/dev/null", f"b/{rel}"))
    if args.dry_run:
        print(f"dry run: would write {rel}")
        return 1
    write_atomically(full, new)
    print(f"OK: wrote {rel} ({1 + len(spans)} span(s), {len(metrics)} metric(s) asserted)")
    return 0


def cmd_path(args):
    spec = load_spec(args.spec)
    lang = check_spec(spec)[0]
    base, _, full = target(args.root, spec, lang)
    print(os.path.relpath(full, base))
    return 0


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("render")
    r.add_argument("--dry-run", action="store_true")
    r.add_argument("--force", action="store_true")
    w = sub.add_parser("path")
    for x in (r, w):
        x.add_argument("--spec", required=True)
        x.add_argument("--root", default=".")
    args = p.parse_args(argv)
    try:
        return {"render": cmd_render, "path": cmd_path}[args.cmd](args)
    except Refused as e:
        print(f"REFUSED: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
